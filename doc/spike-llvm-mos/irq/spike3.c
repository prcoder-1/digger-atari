/*
 * Прерывания на llvm-mos: считает ли наш обработчик кадры.
 *
 * Граница экрана краснеет сразу и зеленеет, когда счётчик кадров перевалит за
 * сотню. Если прерывания не работают, она так и останется красной.
 */
#include <stdint.h>

#define COLBK (*(volatile uint8_t *)0xD01A)

extern volatile uint8_t vbi_count;

int main(void)
{
    COLBK = 0x36u;                      /* красный: кадров ещё не было */

    for (;;)
        if (vbi_count > 100u)
            COLBK = 0xC6u;              /* зелёный: обработчик считает */
}
