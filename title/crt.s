; crt.s - обвязка заставки: заголовки кусков XEX, вход и выход.
;
; Заставку не ЗАПУСКАЮТ, а ВЫЗЫВАЮТ: её кусок файла кончается вектором INITAD
; ($02E2), и загрузчик DOS делает по нему jsr, а дождавшись rts, грузит
; остальные куски файла - саму игру - поверх заставки и запускает её через
; RUNAD.
;
; Поэтому стартового кода библиотеки cc65 здесь нет, и всё, что он обычно
; делает, приходится делать самому: поставить указатель стека Си и обнулить
; BSS. Инициализированные данные (DATA) грузятся из файла как есть.

        .export _title_entry
        .import _title_main
        .import __BSS_RUN__, __BSS_SIZE__
        .import __TSTACKTOP__
        .importzp sp, ptr1, ptr2

; --- признак двоичного файла ------------------------------------------------
        .segment "TEXEHDR"
        .word   $FFFF

; --- заголовок куска с обложкой ---------------------------------------------
; Обложка грузится ПРЯМО в экранную память ($9000): копировать её потом
; некуда и незачем, а лишних 7680 байт в памяти заставки нет.
        .import __COVER_LOAD__, __COVER_SIZE__

        .segment "COVERHDR"
        .word   __COVER_LOAD__
        .word   __COVER_LOAD__ + __COVER_SIZE__ - 1

; --- заголовок куска с кодом ------------------------------------------------
; Конец куска - НАЧАЛО BSS, а не конец области: BSS в файл не пишется, и
; заявленный размер куска обязан совпадать с тем, сколько байт в файле лежит.
; Так же считает и штатный заголовок библиотеки cc65.
        .import __TMAIN_START__, __BSS_LOAD__

        .segment "MAINHDR"
        .word   __TMAIN_START__
        .word   __BSS_LOAD__ - 1

; --- точка входа ------------------------------------------------------------
        .segment "STARTUP"
_title_entry:
        ; Стек Си растёт ВНИЗ от вершины
        lda     #<__TSTACKTOP__
        sta     sp
        lda     #>__TSTACKTOP__
        sta     sp+1

        ; Обнулить BSS: стартовый код библиотеки сюда не дотягивается
        ; Указатель и счётчик - в нулевой странице библиотеки: держать их в
        ; своей BSS нельзя, цикл затёр бы сам себя на первом же обороте.
        lda     #<__BSS_RUN__
        sta     ptr1
        lda     #>__BSS_RUN__
        sta     ptr1+1
        lda     #<__BSS_SIZE__
        sta     ptr2
        lda     #>__BSS_SIZE__
        sta     ptr2+1
        lda     #0
        ldy     #0
bss_lp: ldx     ptr2
        bne     :+
        ldx     ptr2+1
        beq     bss_done
        dec     ptr2+1
:       dec     ptr2
        sta     (ptr1),y
        iny
        bne     bss_lp
        inc     ptr1+1
        bne     bss_lp
bss_done:

        jsr     _title_main
        rts                             ; обратно в загрузчик DOS

; --- вектор INITAD последним куском файла -----------------------------------
        .segment "TRAILER"
        .word   $02E2
        .word   $02E3
        .word   _title_entry
