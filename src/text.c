/*
 * text.c - вывод цифр и букв в кадровый буфер ANTIC F.
 *
 * Буквы берутся из знакогенератора ПЗУ по адресу $E000: он однобитный, 8x8 на
 * символ, то есть в режиме 320 точек лёг бы ровно в один байт. Но тогда
 * надпись вышла бы вдвое мельче, чем была при 160 точках, поэтому каждая
 * точка удваивается: полубайт глифа (4 точки) даёт байт экрана (8 точек), а
 * символ - два байта.
 *
 * Таблица удвоения постоянна. Раньше она строилась в text_init() под нужный
 * индекс цвета, но при одном бите на точку цвета у надписи нет: оттенок задаёт
 * COLPF2 на всю строку растра сразу. Красной панель счёта делает не этот код,
 * а прерывание по строке (src/dli.s).
 */
#include "text.h"
#include "screen.h"
#include "blit.h"

/*
 * Статические данные модуля уезжают в ОЗУ под ПЗУ: MAIN забит под завязку.
 * Обнуляет этот сегмент clear_hi_bss() первым делом в main - стартовый код
 * cc65 сюда не дотягивается, он чистит только сегмент BSS.
 */
#ifdef __CC65__
#pragma bss-name (push, "BSS_HI")
#endif




/*
 * Цифры счёта берутся из шрифта ОРИГИНАЛА, а не из знакогенератора ПЗУ.
 * Цифра 12 точек не ложится на границу байта (байт - 8 точек), поэтому она
 * лежит в ячейке 16 точек = 2 байта с полем по 2 точки с каждой стороны.
 * Данные сплошные, без маски: соседние ячейки не перекрываются, и
 * непрозрачный вывод их не портит.
 */
extern const uint8_t font_digits[];
extern const uint8_t font_alpha[];

#define FONT_BYTES  (FONT_W * FONT_H)

void text_digit(uint8_t x_byte, uint8_t y, uint8_t d)
{
    bl_x = x_byte;
    bl_y = y;
    bl_w = FONT_W;
    bl_h = FONT_H;
    bl_src = font_digits + (unsigned)(d & 0x0Fu) * FONT_BYTES;
    blit_plain();
}

/*
 * Порядок букв в font_alpha - тот же, что в ALPHA у tools/font2c.py. Там их
 * ровно столько, сколько нужно надписям игры: GAME OVER и PRESS ANY KEY.
 * Весь алфавит не берётся из-за области, куда грузится шрифт, - разбор там же,
 * в font2c.py. Правится это ТОЛЬКО парой: строка здесь и ALPHA там.
 */
static const char alpha_order[] = "AEGKMNOPRSVY";

/*
 * Строка шрифтом ИГРЫ, а не знакогенератором ПЗУ.
 *
 * Раньше буквы брались из ПЗУ по $E000 - они мельче и другого рисунка, надпись
 * выбивалась из оформления. Теперь и цифры, и буквы идут из одного шрифта
 * оригинала (assets/font.s), ячейка 16 точек, двенадцать строк.
 *
 * Неизвестный знак - пробел: место занимается, ничего не рисуется.
 */
void text_string(uint8_t x_byte, uint8_t y, const char *s)
{
    while (*s) {
        char c = *s++;
        const uint8_t *g = 0;

        if (c >= '0' && c <= '9') {
            g = font_digits + (unsigned)(c - '0') * FONT_BYTES;
        } else {
            uint8_t i;
            for (i = 0; alpha_order[i]; ++i)
                if (alpha_order[i] == c) {
                    g = font_alpha + (unsigned)i * FONT_BYTES;
                    break;
                }
        }

        if (g) {
            bl_x = x_byte;
            bl_y = y;
            bl_w = FONT_W;
            bl_h = FONT_H;
            bl_src = g;
            blit_plain();
        }
        x_byte += 2u;
    }
}

/*
 * Счёт хранится упакованным BCD в трёх байтах (шесть знаков), как и в
 * оригинале, где потолок 999999. Так сложение делается командой ADC в
 * десятичном режиме, а вывод не требует ни одного деления - в отличие от
 * 32-битного счёта БК-порта, где print_dec вычитал степени десятки.
 */
void text_bcd6(uint8_t x_byte, uint8_t y, const uint8_t *bcd)
{
    uint8_t i;
    for (i = 0; i < 3u; ++i) {
        text_digit(x_byte, y, (uint8_t)(bcd[i] >> 4));
        text_digit((uint8_t)(x_byte + FONT_W), y, (uint8_t)(bcd[i] & 0x0Fu));
        x_byte += (uint8_t)(2u * FONT_W);
    }
}

#ifdef __CC65__
#pragma bss-name (pop)
#endif
