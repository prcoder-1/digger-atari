; vbi.s - отложенное прерывание кадрового гасящего импульса.
;
; Ставится через SETVBV с номером вектора 7 (VVBLKD, отложенный VBI) и
; завершается переходом на XITVBV. Отложенный VBI выполняется после второй
; стадии VBI операционной системы, поэтому теневые ячейки STICK0/STRIG0
; к этому моменту уже обновлены и их достаточно просто защёлкнуть.
;
; Обработчик написан на ассемблере и НИКОГДА не вызывает код на Си:
; программный стек cc65 не реентерабелен.
;
; Здесь же будет тикать проигрыватель музыки и звуковых эффектов (M6, M7).

        .export _vbi_install, _vbi_remove
        .export _vbi_frame, _vbi_stick, _vbi_trig

        .import _sfx_env_tick, _music_tick
        .import _dli_vbi

; Вектор ставится записью напрямую, а не вызовом SETVBV ($E45C).
;
; Причина: под целью atarixl ПЗУ операционной системы выключается, и прямой
; вызов $E45C выполнил бы мусор в ОЗУ; штатная обёртка cc65 называется
; по-разному в зависимости от цели. Запись напрямую работает одинаково на
; обеих целях.
;
; SETVBV нужен был только чтобы обновление двух байт вектора не попало
; на середину кадрового прерывания. То же самое достигается снятием
; разрешения прерывания в NMIEN на время записи: NMIEN только для записи,
; поэтому значение восстанавливается константой, а не чтением.

XITVBV  = $E462
VVBLKD  = $0224
NMIEN   = $D40E
; $80 строчное + $40 кадровое. Строчное здесь обязано быть: NMIEN только для
; записи, значение восстанавливается константой, и с одним $40 постановка или
; снятие кадрового вектора гасила бы DLI панели счёта (см. src/dli.s).
NMIEN_VBI = $C0
STICK0  = $0278
STRIG0  = $0284
PORTB   = $D301

        .segment "DATA"
_vbi_frame:  .byte 0        ; счётчик кадров, растёт 50 раз в секунду
_vbi_stick:  .byte $0F      ; защёлка джойстика (биты активны нулём)
_vbi_trig:   .byte 1        ; защёлка кнопки (0 = нажата)
old_vbi:     .word 0        ; прежний вектор, чтобы вернуть при выходе

        .segment "CODE"

; void vbi_install(void)
_vbi_install:
        lda     VVBLKD
        sta     old_vbi
        lda     VVBLKD+1
        sta     old_vbi+1
        lda     #<handler
        ldx     #>handler
        jmp     set_vector

; void vbi_remove(void)
_vbi_remove:
        lda     old_vbi
        ldx     old_vbi+1
        ; далее по коду set_vector

; A = младший байт вектора, X = старший
set_vector:
        pha
        lda     #0
        sta     NMIEN                   ; запретить кадровое прерывание
        pla
        sta     VVBLKD
        stx     VVBLKD+1
        lda     #NMIEN_VBI
        sta     NMIEN                   ; разрешить обратно
        rts

; Обёртка NMI цели atarixl включает ПЗУ на время прерывания, а таблицы нот
; лежат под ним (сегмент LEVELS). Поэтому на время обработчика ПЗУ снова
; выключается: иначе с 0c608ba музыка играла байты ПЗУ вместо нот. Выход в
; XITVBV - код ПЗУ, перед ним PORTB возвращается как было.
handler:
        lda     PORTB
        pha
        and     #$FE
        sta     PORTB
        jsr     _dli_vbi                ; цепочка прерываний по строке - с начала
        jsr     _sfx_env_tick           ; огибающая идёт по кадрам, 50 Гц
        jsr     _music_tick             ; и музыка тоже: темп задан в кадрах
        jsr     shake_tick              ; тряска поля при ударе мешка
        inc     _vbi_frame
        lda     STICK0
        sta     _vbi_stick
        lda     STRIG0
        sta     _vbi_trig
        pla
        sta     PORTB
        jmp     XITVBV

; ---------------------------------------------------------------------------
; Тряска поля при ударе мешка об землю.
;
; В дисплей-листе пустые строки перед картинкой заданы ЧЕТЫРЬМЯ командами:
; 8 + 8 + 7 + 1 (см. build_dlist в src/screen.c). Первые три постоянны, а
; четвёртая - управляемая: команда пустых строк задаёт от одной до восьми,
; поэтому одним байтом картинка опускается на 0..7 строк растра. Перестраивать
; список не нужно, а значит и рвать привязку прерываний к строкам.
;
; Шаг идёт ПО КАДРАМ, а не по игровому такту: на 10 Гц вся тряска заняла бы
; больше полусекунды и читалась бы как медленный рывок, а не как удар.
;
; В порте на БК то же делалось регистром вертикального сдвига и длилось один
; такт на одну строку. Здесь взят короткий отскок вниз и обратно.
;
; ВАЖНО: опускается только поле. Аппаратные спрайты стоят по абсолютным
; строкам растра и за картинкой не идут, поэтому на время тряски Диггер и
; враги отстают от поля на те же строки. Тряска короткая, и на глаз это
; читается как часть удара.
; ---------------------------------------------------------------------------
        .export _screen_shake
        .import _dlist

        .segment "DATA"
; Читается индексом от 8 до 1, то есть задом наперёд: получается
; 1, 2, 3, 3, 2, 1, 0, 0 строк смещения.
shake_tbl: .byte $00,$00,$10,$20,$30,$30,$20,$10
shake_cnt: .byte 0

        .segment "CODE"

; void screen_shake(void)
_screen_shake:
        lda     #8
        sta     shake_cnt
        rts

shake_tick:
        ldx     shake_cnt
        beq     shk_done
        dec     shake_cnt
        lda     shake_tbl-1,x
        sta     _dlist+3
shk_done:
        rts
