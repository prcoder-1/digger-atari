/*
 * bugs.h - враги: Ноббины и Хоббины.
 *
 * Ноббин ходит только по прокопанным ходам, Хоббин прогрызает землю сам.
 * Оба выбирают направление, только стоя ровно в клетке; между клетками
 * направление не меняется - иначе они выходили бы из коридоров боком.
 *
 * Порядок направлений строится по взаимному положению с Диггером: сначала
 * та ось, по которой расстояние больше. Обратное направление ставится
 * последним, чтобы враг не топтался на месте. В бонус-режиме порядок
 * переворачивается - враги убегают.
 */
#ifndef BUGS_H
#define BUGS_H

#include <stdint.h>
#include "hw.h"

#define MAX_BUGS    5u

#define BUG_NONE    0u
#define BUG_ALIVE   1u

#define BUG_NOBBIN  0u          /* ходит по ходам   */
#define BUG_HOBBIN  1u          /* грызёт землю     */

typedef struct {
    uint8_t state;
    uint8_t kind;
    uint8_t x;                  /* подшаги          */
    uint8_t y;                  /* строки растра    */
    uint8_t dir;
    uint8_t frame;
    uint8_t count;              /* тактов в текущем облике */
} bug_t;

/*
 * Пороги превращения перенесены из порта на БК без пересчёта: наш такт
 * идёт на 9% медленнее, и счётчики, выраженные в тактах, остаются верны.
 * Чем выше сложность, тем дольше враг остаётся Хоббином и тем быстрее
 * им становится.
 */
#define HOBBIN_TICKS(d)   (30u + 2u * (d))   /* Хоббин -> Ноббин */
#define NOBBIN_TICKS(d)   (21u - (d))        /* Ноббин -> Хоббин */

extern bug_t bugs[MAX_BUGS];
extern uint8_t bugs_active;

/* Сколько врагов ещё родится на этом уровне */
extern uint8_t bugs_left_to_spawn(void);

void bugs_init(uint8_t screen, uint8_t difficulty);
void bugs_tick(void);

/* Вывод врагов: зовётся ПОСЛЕДНИМ в такте, см. bugs.c */
void bugs_draw_all(void);

/* Убрать живых врагов после гибели Диггера, не восстанавливая их запас */
void bugs_respawn(void);

/* Столкнулся ли какой-нибудь враг с Диггером */
/* Какой враг столкнулся с Диггером: номер или 0xFF. В бонус-режиме это
 * не гибель, а добыча, поэтому нужен именно номер, а не просто признак. */
uint8_t bugs_hit_man(void);
#define BUG_NO_HIT  0xFFu

/* В бонус-режиме враги разбегаются: порядок направлений переворачивается */
extern uint8_t bugs_fleeing;

/* Убрать врага с поля (съеден в бонус-режиме) */
void bugs_remove(uint8_t i);

#endif /* BUGS_H */
