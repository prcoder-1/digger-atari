; music.s - фоновая музыка на канале 3 POKEY.
;
; Тикает из кадрового прерывания, то есть 50 раз в секунду. Порт на БК был
; вынужден дробить ноту на кусочки и доигрывать их в остатке кадрового
; времени, потому что там звук занимал процессор целиком. POKEY держит тон
; сам, поэтому от всего планировщика остаётся один счётчик длительности.
;
; Темп задаётся накопителем в формате 8.8: длительность восьмой ноты хранится
; с дробной частью, из счётчика раз в кадр вычитается ровно единица. Иначе
; восьмая укладывалась бы в целое число кадров, и темп уезжал бы на проценты:
; при 50 Гц восьмая мелодии Popcorn - это 9.08 кадра, а не 9.
;
; Кодировка ноты перенесена из порта на БК без изменений:
;   n < 14   восьмая, высота n      n + 14   четверть
;   n + 28   пять восьмых           $FF      конец, мелодия зациклится

        .export _music_start, _music_stop, _music_tick
        .export _music_notes_played
        .export _mus_atk, _mus_hlvl, _mus_hrate, _mus_drate, _mus_hcnt

        .import _music_audf

AUDF3   = $D204
AUDC3   = $D205
AUDF4   = $D206
AUDC4   = $D207

MUS_TONE = $A0                  ; чистый тон, громкость подставляет огибающая
MUS_VOL  = $A8                  ; ровная громкость для одиночной ноты

; Потолок громкости фоновой мелодии. У POKEY шкала 0..15, и поначалу атака
; упиралась в самый верх - музыка забивала эффекты. Опускали дважды: сперва до
; десяти, потом до семи.
;
; Уровни удержания заданы из Си (music_shape в sfx.c) и опускаются там же в той
; же пропорции - иначе тише становилась бы только атака, а тянущаяся часть ноты
; оставалась бы прежней.
MUS_VOL_MAX = 7

; Фазы огибающей - те же три, что в оригинале (chk_music в Work/TH.C)
ENV_ATTACK = 0
ENV_HOLD   = 1
ENV_DECAY  = 2

        .segment "ZEROPAGE"
mus_ptr:  .res 2                ; текущая позиция в мелодии
mus_base: .res 2                ; начало мелодии, чтобы зациклить
mus_left: .res 2                ; кадров до следующей ноты, формат 8.8
mus_egt:  .res 2                ; длительность восьмой, формат 8.8

        .segment "DATA"
mus_on:   .byte 0

;
; Огибающая ноты. В оригинале мелодия идёт вторым источником звука - широтно-
; импульсным, - и у каждой ноты своя форма: ширина импульса нарастает до
; attack_level, затем спадает к hold_level, а после hold_count тиков падает в
; ноль. Ровного тона там нет ни одной ноты, и именно это даёт живое звучание.
;
; На POKEY ширины импульса нет, зато есть настоящая громкость 0..15, поэтому
; та же форма кладётся на неё. Громкость держится в формате 8.8: шаги
; оригинала мельче одной ступени POKEY, и без дробной части атака вышла бы
; мгновенной, а спад - ступенчатым.
;
; Числа приходят из Си (music_select), а не зашиты здесь: у каждой мелодии
; своя форма, а ca65 не читает sfx.c.
;
mus_vol:  .word 0               ; текущая громкость, 8.8
mus_env:  .byte 0               ; фаза огибающей
mus_audf: .byte 0               ; делитель текущей ноты, БЕЗ вибрато
vib_ph:   .byte 0               ; фаза вибрато, растёт раз в кадр
tune_audf: .byte 0              ; то же для марша и фанфары (music_note)
tune_on:  .byte 0               ; звучит ли марш или фанфара
n2_on:    .byte 0               ; звучит ли второй голос фанфары
mus_hcnt_left: .byte 0          ; кадров до перехода в спад
_mus_atk:   .word 0             ; прибавка за кадр в атаке
_mus_hlvl:  .word 0             ; уровень удержания
_mus_hrate: .word 0             ; убавка за кадр в удержании
_mus_drate: .word 0             ; убавка за кадр в спаде
_mus_hcnt:  .byte 0             ; кадров удержания до спада
; Накопительный счётчик сыгранных нот: по нему видно, что проигрыватель
; движется, даже если высоты окажутся неверными.
_music_notes_played: .byte 0

        .segment "CODE"

; void __fastcall__ music_start(void)  - мелодия и темп берутся из mus_base/mus_egt,
; их выставляет обёртка на Си через music_select
_music_start:
        lda     mus_base
        sta     mus_ptr
        lda     mus_base+1
        sta     mus_ptr+1
        lda     #0
        sta     mus_left
        sta     mus_left+1              ; первая нота зазвучит сразу
        sta     _music_notes_played
        lda     #1
        sta     mus_on
        rts

; void __fastcall__ music_note(unsigned char audf)
;
; Выдаёт одиночную ноту на канал мелодии, пока проигрыватель остановлен.
; Нужна для траурного марша: голос эффектов работает связанной 16-битной
; парой от тактовой 1.79 МГц, а таблица периодов мелодии рассчитана на
; одиночный канал от базы 64 кГц - через sfx_play марш звучал октавой выше.
        .export _music_note
_music_note:
        sta     AUDF3
        sta     tune_audf               ; основа для качания, см. tune_vib_do
        lda     #MUS_VOL
        sta     AUDC3
        lda     #1
        sta     tune_on                 ; марш и фанфара тоже качаются
        rts

; Отложенный запуск второго голоса. Оба голоса, взятые ровно вместе, слышны
; как один расстроенный тон; небольшое запаздывание разводит их, и фанфара
; звучит как два инструмента. Задержка отсчитывается КАДРАМИ в music_tick -
; игровой такт (10 Гц) для этого слишком груб, на нём голоса разъехались бы
; на десятую долю секунды.
N2_DELAY = 3                    ; кадров, то есть около 60 мс

        .segment "DATA"
n2_audf:  .byte 0               ; что выдать вторым голосом
n2_left:  .byte 0               ; кадров до выдачи, 0 - нечего ждать

        .segment "CODE"

; void __fastcall__ music_note2(unsigned char audf)
;
; Второй голос - на канале 4. Фанфару в конце уровня оригинал играет ДВУМЯ
; голосами сразу: прямоугольным на t_period и широтно-импульсным на
; t_period + 35, то есть тем же тоном чуть ниже. Между ними биения, отчего
; фанфара звучит объёмно, а не как одинокий писк.
;
; В единицах POKEY эта добавка ровно +1 и не зависит от ноты: период PIT
; переводится в делитель как P/37.68, а 35/37.68 = 0.93.
        .export _music_note2
_music_note2:
        sta     n2_audf
        lda     #N2_DELAY
        sta     n2_left
        rts

; Довыдать второй голос, когда его задержка вышла. Зовётся каждый кадр из
; music_tick, ДО проверки mus_on: фанфара играет при остановленном
; проигрывателе фоновой мелодии.
n2_tick:
        lda     n2_left
        beq     n2_done
        dec     n2_left
        bne     n2_done
        lda     n2_audf
        sta     AUDF4
        lda     #MUS_VOL
        sta     AUDC4
        lda     #1
        sta     n2_on                   ; второй голос зазвучал - качать и его
n2_done:
        rts

_music_stop:
        lda     #0
        sta     mus_on
        sta     AUDC3
        sta     AUDC4                   ; и второй голос фанфары
        sta     n2_left                 ; и отложенный запуск отменяется
        sta     tune_on                 ; и качание марша прекращается
        sta     n2_on
        rts

; Вызывается из кадрового прерывания
_music_tick:
        jsr     n2_tick                 ; второй голос фанфары идёт с задержкой
        lda     mus_on
        bne     :+

; Мелодия молчит - но может звучать марш или фанфара. Они идут не отсюда, а
; из tune_tick в main.c, и ноту ставят раз в игровой такт (10 Гц). Качать её
; всё равно надо здесь: кадровое прерывание - единственное, что тикает 50 раз
; в секунду.
        lda     tune_on
        beq     tv_done
        jsr     vib_step
        clc
        lda     tune_audf
        adc     vib_tbl,y
        sta     AUDF3
        lda     n2_on                   ; второй голос фанфары, если зазвучал
        beq     tv_done
        clc
        lda     n2_audf
        adc     vib_tbl,y
        sta     AUDF4
tv_done:
        rts
:
        ; mus_left -= 1.0 (то есть $0100 в формате 8.8)
        sec
        lda     mus_left+1
        sbc     #1
        sta     mus_left+1
        bcs     mus_done                ; ещё звучит

; --- пора брать следующую ноту ---
mus_next:
        ldy     #0
        lda     (mus_ptr),y
        cmp     #$FF
        bne     :+
        lda     mus_base                ; конец - зациклить
        sta     mus_ptr
        lda     mus_base+1
        sta     mus_ptr+1
        lda     (mus_ptr),y
:
        ; длительность: 1, 2 или 5 восьмых по диапазону кода ноты
        ldx     #1
        cmp     #28
        bcc     :+
        sbc     #28
        ldx     #5
        bne     mus_have
:
        cmp     #14
        bcc     mus_have
        sbc     #14
        ldx     #2
mus_have:
        tay                             ; Y = высота
        lda     _music_audf,y
        sta     mus_audf                ; делитель запоминается: в AUDF3 его
                                        ; каждый кадр кладёт вибрато, см. mus_out
        sta     AUDF3
        lda     #0
        sta     vib_ph                  ; нота начинается с середины качания
        lda     #0                      ; нота начинается с тишины и нарастает
        sta     mus_vol
        sta     mus_vol+1
        sta     mus_env                 ; ENV_ATTACK
        lda     _mus_hcnt
        sta     mus_hcnt_left
        inc     _music_notes_played

        ; mus_left += mus_egt * X, умножение сложением: X не больше пяти.
        ;
        ; Именно ПРИБАВЛЯЕТСЯ к остатку, а не присваивается. Счётчик к этому
        ; моменту уже ушёл чуть ниже нуля, и этот остаток - дробная часть
        ; длительности плюс кадр, на котором произошло переполнение. Если его
        ; отбросить, каждая нота удлиняется на кадр и теряет дробную часть:
        ; измерено 10.4 кадра на восьмую вместо 9.1, то есть темп на 13% ниже.
mus_mul:
        clc
        lda     mus_left
        adc     mus_egt
        sta     mus_left
        lda     mus_left+1
        adc     mus_egt+1
        sta     mus_left+1
        dex
        bne     mus_mul

        ; шагнуть на следующую ноту
        inc     mus_ptr
        bne     mus_done
        inc     mus_ptr+1

; --- огибающая: раз в кадр, независимо от того, сменилась ли нота ---
mus_done:
        lda     mus_env
        cmp     #ENV_DECAY
        beq     mus_decay
        cmp     #ENV_HOLD
        beq     mus_hold

; АТАКА: громкость растёт, пока не упрётся в потолок
        clc
        lda     mus_vol
        adc     _mus_atk
        sta     mus_vol
        lda     mus_vol+1
        adc     _mus_atk+1
        sta     mus_vol+1
        cmp     #MUS_VOL_MAX            ; потолок громкости мелодии
        bcc     mus_out
        lda     #MUS_VOL_MAX
        sta     mus_vol+1
        lda     #0
        sta     mus_vol
        lda     #ENV_HOLD
        sta     mus_env
        jmp     mus_out

; УДЕРЖАНИЕ: громкость сползает к уровню удержания и стоит там,
; пока не выйдет отпущенное ноте время
mus_hold:
        sec
        lda     mus_vol
        sbc     _mus_hrate
        tax
        lda     mus_vol+1
        sbc     _mus_hrate+1
        bcc     mus_hclamp              ; ушли ниже нуля
        cmp     _mus_hlvl+1
        bcc     mus_hclamp
        bne     mus_hstore
        cpx     _mus_hlvl
        bcc     mus_hclamp
mus_hstore:
        stx     mus_vol
        sta     mus_vol+1
        jmp     mus_hcheck
mus_hclamp:
        lda     _mus_hlvl
        sta     mus_vol
        lda     _mus_hlvl+1
        sta     mus_vol+1
mus_hcheck:
        lda     mus_hcnt_left
        beq     :+
        dec     mus_hcnt_left
        bne     mus_out
:       lda     #ENV_DECAY
        sta     mus_env
        jmp     mus_out

; СПАД: до нуля, дальше нота молчит
mus_decay:
        sec
        lda     mus_vol
        sbc     _mus_drate
        tax
        lda     mus_vol+1
        sbc     _mus_drate+1
        bcs     :+
        lda     #0                      ; ниже нуля - значит тишина
        tax
:       stx     mus_vol
        sta     mus_vol+1

; Выдать громкость.
;
; Мелодия звучит ПОВЕРХ эффектов. В оригинале так не выходило: там источник
; звука один на двоих, и ШИМ-голос музыки выключался, едва любой эффект занял
; основной канал. У POKEY каналы отдельные, глушить музыку незачем.
mus_out:
        lda     mus_vol+1
        ora     #MUS_TONE
        sta     AUDC3

; --- ВИБРАТО ---
;
; В оригинале мелодия идёт широтно-импульсным голосом, и ширина импульса плывёт
; ВНУТРИ каждой ноты (chk_music в Work/TH.C): тембр всё время меняется, отчего
; звук и слышится живым, пульсирующим. У POKEY ширины импульса нет - тон там
; ровный от начала до конца ноты, и мелодия выходила мёртвой.
;
; Порт на БК тут не помощник: он играет ноту постоянной скважностью 1
; (sound_pwm(period, chunk, 1)) и никакого качания не делает.
;
; Поэтому взято ближайшее, что POKEY даёт даром, - качание ВЫСОТЫ. Делитель
; ноты раз в кадр сдвигается на единицу по треугольнику из восьми кадров, то
; есть 50/8 = 6.25 Гц - обычная для вибрато скорость.
;
; Глубина в одну единицу делителя выбрана не на глаз: делители нот мелодии
; лежат в пределах 53..214, значит шаг в единицу - это от 0.5% до 1.9% по
; частоте, или от 8 до 33 центов. Живое вибрато - примерно столько и есть,
; и одна и та же глубина годится на весь диапазон.
;
; Фанфару и марш это не задевает: у них свой путь (_music_note), а music_tick
; при остановленной мелодии выходит по mus_on ещё в начале.
        jsr     vib_step
        clc
        lda     mus_audf
        adc     vib_tbl,y
        sta     AUDF3
        rts

; Шаг фазы качания. Возвращает индекс в Y.
;
; Период ШЕСТЬ кадров, то есть 50/6 = 8.3 Гц. Было восемь кадров (6.25 Гц) -
; подняли по просьбе: на слух так живее.
VIB_LEN = 6
vib_step:
        ldy     vib_ph
        iny
        cpy     #VIB_LEN
        bcc     :+
        ldy     #0
:       sty     vib_ph
        rts

; Треугольник качания на шесть шагов: ноль, вверх, вверх, ноль, вниз, вниз.
; $FF - это минус единица.
vib_tbl:
        .byte   $00,$01,$01,$00,$FF,$FF

; Мелодию и темп выставляет обёртка music_select в sfx.c: она пишет прямо
; в mus_base и mus_egt, поэтому отдельной процедуры-установщика не нужно.
        .export _mus_base, _mus_egt
_mus_base = mus_base
_mus_egt  = mus_egt
