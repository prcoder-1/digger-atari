/*
 * hw.h - железо ATARI 65XE/130XE и геометрия экрана для Digger.
 *
 * Регистры берутся из cc65 <atari.h> (структуры ANTIC/GTIA_WRITE/POKEY_WRITE),
 * здесь только то, что удобнее иметь константами, и вся геометрия поля.
 *
 * Геометрия совпадает с оригиналом для PC ОДИН К ОДНОМУ: и там и здесь
 * 320 точек в строке.
 *
 *              оригинал PC      Atari
 *   экран      320 x 200        320 x 208
 *   клетка     20 x 18          20 x 18
 *   спрайт     16 x 15          16 x 15  (2 байта)
 *   подшаг X   4 (5 на клетку)  4 (5 на клетку)
 *   подшаг Y   3 (6 на клетку)  3 строки (6 на клетку)
 *   поле       300 x 180        300 x 180
 *
 * Запас 4 точки по бокам и 3 строки по вертикали между спрайтом и клеткой -
 * это разделители земли между клетками, которых лишился порт на БК.
 *
 * Раньше поле шло в ANTIC E: 160 точек при четырёх красках, то есть вдвое уже
 * оригинала. Сравнение обоих режимов снимками и причины выбора - в
 * doc/graphics.md.
 */
#ifndef HW_H
#define HW_H

#include <stdint.h>

/* ---------------------------------------------------------------- экран */

/*
 * ANTIC F, НОРМАЛЬНОЕ поле: 40 байт по одному биту на точку = 320 точек.
 * Широкое поле (48 байт) не используется: измерено на M0, что видны только
 * байты 3..44 - по 3 байта с каждого края уходит за пределы картинки.
 */
#define SCR_STRIDE      40u             /* байт в строке растра            */
#define SCR_LINES       208u            /* строк растра                    */
#define SCR_WIDTH_PX    320u            /* точек по горизонтали            */
#define SCR_PX_PER_BYTE 8u              /* 1 бит на точку                  */

/* Прогоны буфера между LMS (ни один не пересекает границу 4096) */
#define SCR_RUN0_LINES  102u            /* строки   0..101 -> $9010        */
#define SCR_RUN1_LINES  102u            /* строки 102..203 -> $A000        */
#define SCR_RUN2_LINES  4u              /* строки 204..207 -> $B000        */

/* --------------------------------------------------------------- поле */

#define W_MAX           15u             /* клеток по горизонтали           */
#define H_MAX           10u             /* клеток по вертикали             */

#define CELL_W_PX       20u
#define CELL_H_PX       18u

#define SPRITE_W_PX     16u             /* 2 байта                         */
#define SPRITE_W_BYTES  2u
#define SPRITE_H        15u

/*
 * x_graph считается в ПОДШАГАХ по 4 точки (полбайта), y_graph - в строках
 * растра. Отсюда: байт экрана = x_graph >> 1, фаза сдвига = x_graph & 1.
 * Спрайт хранится в двух предсдвинутых фазах: фаза 0 - 2 байта, фаза 1 - 3.
 */
#define SUBSTEP_X_PX    4u              /* точек в подшаге по X            */
#define SUBSTEP_Y_LINES 3u              /* строк растра в подшаге по Y     */

#define POS_X_STEP      5u              /* подшагов в клетке по X          */
#define POS_Y_STEP      6u              /* подшагов в клетке по Y          */

/*
 * Подшаг ровно вдвое короче байта экрана, поэтому все координаты и ширины по
 * X держатся в подшагах: перевод в байты - это один сдвиг, а в пикселях левый
 * край правой клетки поля равен 288 и уже не помещается в байт.
 */
#define SUBSTEP_PER_BYTE 2u
#define SPRITE_W_SUB    (SPRITE_W_PX / SUBSTEP_X_PX)    /* 4 подшага */
#define CELL_W_SUB      POS_X_STEP                      /* 5 подшагов */
#define MOVE_X_STEP     1u
#define MOVE_Y_STEP     SUBSTEP_Y_LINES /* шаг по Y сразу в строках растра */

/* HUD занимает строки 0..27, поле - строки 28..207 */
#define HUD_LINES       28u

/*
 * Красная полоса панели КОРОЧЕ отведённых ей строк: счёт и значки жизней
 * укладываются в строки 2..13 (замерено по снимку), а строки 14..27 пусты.
 * Полоса обрезана по содержимому с запасом в две строки снизу, оставшиеся
 * строки уходят под цвета поля и читаются как отступ над землёй.
 */
#define HUD_BAND_LINES  16u

/* Насколько выше границы ставится бит DLI, чтобы краски успели смениться
 * ровно на строке HUD_BAND_LINES; подобрано по снимку, см. build_dlist в
 * screen.c */
#define DLI_LEAD        2u

/*
 * Сетка прерываний по полю: горизонтальная позиция игроков-врагов
 * перезагружается каждые DLI_GRID строк, начиная с FIELD_Y_OFFSET. Сетка
 * НЕПОДВИЖНА - биты ставятся один раз при построении дисплей-листа и больше
 * не трогаются никогда. Почему именно так, а не по биту на врага, - в шапке
 * src/pmgbug.c.
 *
 * Шаг 8 выбран степенью двойки: номер клетки сетки считается сдвигом, а не
 * делением. Строк в поле 180, значит клеток 23: действуют они на строках
 * 28, 36, ... 204.
 */
#define DLI_GRID        8u
#define DLI_GRID_N      23u
#define FIELD_Y_OFFSET  HUD_LINES
#define FIELD_H_LINES   (H_MAX * CELL_H_PX)             /* 180 */

/* Поле начинается с байта 1, то есть с подшага 2 */
#define FIELD_X0_PX     (SUBSTEP_X_PX * 2u)             /* 8 */
#define FIELD_X_OFFSET  2u                              /* подшага */
#define FIELD_W_PX      (W_MAX * CELL_W_PX)             /* 300 */

/* --------------------------------------------------------------- цвета */

/* Байт цвета Atari: оттенок в битах 4-7, яркость в битах 1-3 */
#define ATARI_COLOR(hue, lum)   (uint8_t)(((hue) << 4) | ((lum) & 0x0Eu))

/*
 * В ANTIC F красок полторы. Фон берётся из COLPF2 целиком, а зажжённая точка
 * получает ОТТЕНОК от той же COLPF2 и только ЯРКОСТЬ от COLPF1. Значит на одну
 * строку растра приходится один оттенок, и выбирать можно лишь, насколько
 * светлее фона будет рисунок.
 *
 * Красок ДВЕ ПАРЫ, потому что панель счёта и поле разведены прерыванием по
 * строке (см. src/dli.s): панельная пара живёт в теневых ячейках ОС и
 * восстанавливается кадровым прерыванием к строке 0, полевую кладёт DLI на
 * границе строк 15/16 (HUD_BAND_LINES).
 *
 * Поле - тёмный янтарь: прокопанный ход почти чёрный, земля - почти белая, и
 * это наибольший контраст, какой режим вообще даёт. Оставить землю другого
 * оттенка режим не позволяет, оттенок в строке общий.
 *
 * Яркость фона поля не 0, потому что при нуле оттенок гаснет: $10 неотличим
 * от чистого чёрного $00, и янтаря не остаётся. Нижние ступени: 2 даёт
 * #421000, 4 - #5A2900.
 *
 * Яркость COLPF1 общая для земли и для заливки фигур: в этом режиме она
 * навязывается сверху, игроки отдают лишь оттенок (см. doc/graphics.md).
 *
 * У панели фон на нуле яркости - он читается почти чёрным (#3A0000), оттенок 3
 * нужен надписям. Замерено по снимкам, чем платится за яркость надписей:
 * 8 - #BD737B тускнеет до неразличимого, 10 - самая красная из читаемых,
 * 14 - #FFBDC5, максимальная различимость ценой выцветания в розовый.
 * Оттенки 2 и 4 проверены там же и отпали - первый уходит в кирпичный, второй
 * в лиловый.
 *
 * Младший бит яркости в ATARI_COLOR отбрасывается маской 0x0E: яркость 15 и 14
 * дают один и тот же байт.
 *
 * COLBK здесь только рамка вокруг картинки, к полю отношения не имеет.
 * COLPF0 в этом режиме не участвует вовсе.
 */
#define COL_BACK        ATARI_COLOR(0x0, 0)     /* рамка                    */
#define COL_PF0         ATARI_COLOR(0x0, 0)     /* не участвует             */

#define COL_FIELD_PF2   ATARI_COLOR(0x1, 4)     /* тёмный янтарь, фон поля  */
#define COL_FIELD_PF1   ATARI_COLOR(0x0, 12)    /* яркость рисунка поля     */
#define COL_HUD_PF2     ATARI_COLOR(0x0, 0)     /* панель без оттенка, серая*/
#define COL_HUD_PF1     ATARI_COLOR(0x0, 15)    /* яркость надписей панели  */

/*
 * Цвета фигур в аппаратных спрайтах. Игроков четыре, и они поделены так:
 *
 *      игрок 0   корпус Диггера      краска 2 оригинала
 *      игрок 1   клюв Диггера        краска 1
 *      игрок 2   враг                весь силуэт
 *      игрок 3   враг                весь силуэт
 *
 * Колёса Диггера цвет потеряли: два игрока ушли врагам, а колёса из трёх его
 * красок красились хуже всех - кольцо в одну точку при ячейке игрока в две
 * точки не покрасить, не потеряв форму (tools/spr2atari.py).
 *
 * Заливка ПОДКЛАДЫВАЕТСЯ ПОД рисунок: фигуры по-прежнему выводятся в кадровый
 * буфер на всех 320 точках, а игроки красят их изнутри, оставляя по краю линию
 * из кадрового буфера. Почему нельзя наоборот - см. tools/spr2atari.py.
 *
 * Оттенки взяты у оригинала для PC: там Диггер красный с зелёным клювом и
 * жёлтыми колёсами, а ОБА врага - и Ноббин, и Хоббин - зелёные, с красными
 * ногами и жёлтыми глазами. Различаются они формой, а не цветом, поэтому у
 * обоих игроков-врагов краска одна.
 *
 * Яркость игрокам НАВЯЗЫВАЕТСЯ из COLPF1 там, где бит поля установлен, поэтому
 * все выходят пастельными, и выбирать можно только оттенок; яркость в самом
 * байте цвета ни на что не влияет - заливка целиком лежит под зажжёнными
 * точками.
 */
#define COL_PM_BODY     ATARI_COLOR(0x3, 4)     /* корпус Диггера, красный  */
#define COL_PM_BEAK     ATARI_COLOR(0xC, 8)     /* клюв Диггера, зелёный    */
#define COL_PM_BUG      ATARI_COLOR(0xC, 8)     /* враги, зелёные           */

/*
 * Вишенка собрана из двух половин: КОНТУР идёт в кадровый буфер и держит форму
 * с точностью до точки, а ВНУТРЕННОСТЬ закрашивает аппаратура. Внутри контура
 * кадровый буфер пуст (см. contour() в tools/spr2atari.py), и это условие
 * цвета: у зажжённой точки яркость навязана из COLPF1, и краска под ней
 * выцвела бы в пастельную, как у Диггера и врагов. Сквозь пустую внутренность
 * видна вся краска целиком - и оттенок, и яркость.
 *
 * Красит её COLPF3: четыре снаряда PMG сведены в "пятого игрока" (бит $10 в
 * PRIOR), и краска у них общая. В режиме высокого разрешения COLPF3 не
 * участвует в выводе поля, так что регистр был свободен.
 *
 * Красок всё же две: ветка зелёная, ягоды красные. Одна на кадр - но не одна
 * на строку растра, а граница между веткой и ягодами легла ровно на стык
 * клеток сетки прерываний, и COLPF3 меняется там же, где переставляются
 * позиции врагов (src/dli.s).
 */
#define COL_CHERRY_STEM ATARI_COLOR(0xC, 8)     /* ветка вишенки, зелёная   */
#define COL_CHERRY      ATARI_COLOR(0x3, 10)    /* ягоды вишенки, красные   */

/* -------------------------------------------------------- байты ANTIC */

#define DL_BLANK8       0x70            /* 8 пустых строк растра           */
#define DL_MODE_F       0x0F            /* 320 x 1 x 2 краски              */
#define DL_LMS          0x40            /* + 2 байта адреса                */
#define DL_JVB          0x41            /* переход с ожиданием кадра       */
#define DL_DLI          0x80

/*
 * DMACTL / SDMCTL: выборка дисплей-листа ($02) + нормальное поле ($20) +
 * выборка игроков ($08) + выборка снарядов ($04) + однострочное разрешение
 * ($10). Без последнего байт игрока покрывал бы две строки растра, а подшаг
 * по Y у нас три строки, и позиции стали бы то чётные, то нечётные.
 *
 * Снаряды нужны под вишенку, см. COL_CHERRY: своей выборки у них нет, они
 * идут отдельным битом от игроков.
 */
#define SDMCTL_GAME     0x3E

/* --------------------------------------------------- теневые ячейки ОС */

#define OS_SDMCTL       (*(volatile uint8_t *)0x022Fu)
#define OS_SDLSTL       (*(volatile uint16_t *)0x0230u)
#define OS_GPRIOR       (*(volatile uint8_t *)0x026Fu)  /* -> PRIOR  */
#define OS_PCOLR0       (*(volatile uint8_t *)0x02C0u)  /* -> COLPM0 */
#define OS_PCOLR1       (*(volatile uint8_t *)0x02C1u)  /* -> COLPM1 */
#define OS_PCOLR2       (*(volatile uint8_t *)0x02C2u)  /* -> COLPM2 */
#define OS_PCOLR3       (*(volatile uint8_t *)0x02C3u)  /* -> COLPM3 */
#define OS_COLOR0       (*(volatile uint8_t *)0x02C4u)  /* -> COLPF0 */
#define OS_COLOR1       (*(volatile uint8_t *)0x02C5u)  /* -> COLPF1 */
#define OS_COLOR2       (*(volatile uint8_t *)0x02C6u)  /* -> COLPF2 */
#define OS_COLOR3       (*(volatile uint8_t *)0x02C7u)  /* -> COLPF3 */
#define OS_COLOR4       (*(volatile uint8_t *)0x02C8u)  /* -> COLBK  */
#define OS_RTCLOK2      (*(volatile uint8_t *)0x0014u)  /* счётчик кадров ОС */
#define OS_STICK0       (*(volatile uint8_t *)0x0278u)
#define OS_STRIG0       (*(volatile uint8_t *)0x0284u)
#define OS_CH           (*(volatile uint8_t *)0x02FCu)

/* --------------------------------------------------------- регистры */

#define ANTIC_VCOUNT    (*(volatile uint8_t *)0xD40Bu)
#define ANTIC_WSYNC     (*(volatile uint8_t *)0xD40Au)
#define GTIA_COLBK      (*(volatile uint8_t *)0xD01Au)

/* Снаряды PMG: по два бита на снаряд в одном байте, позиции раздельные */
#define GTIA_HPOSM0     (*(volatile uint8_t *)0xD004u)
#define GTIA_HPOSM1     (*(volatile uint8_t *)0xD005u)
#define GTIA_HPOSM2     (*(volatile uint8_t *)0xD006u)
#define GTIA_HPOSM3     (*(volatile uint8_t *)0xD007u)
#define GTIA_SIZEM      (*(volatile uint8_t *)0xD00Cu)
#define GTIA_CONSOL     (*(volatile uint8_t *)0xD01Fu)

#endif /* HW_H */
