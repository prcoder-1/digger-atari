static uint8_t step_no;
static uint16_t step_left;
static uint8_t finished;
uint16_t demo_tick;

void demo_init(void)
{
    step_no = 0;
    step_left = route[0].ticks;
    finished = 0;
    demo_tick = 0;
}

/*
 * По окончании маршрута счётчик тактов замирает: иначе телеметрия зависела бы
 * от того, в какой момент снят кадр, и проверка не была бы воспроизводимой.
 *
 * Шаг с ненулевой длительностью отрабатывает её и уступает место следующему;
 * шаг с НУЛЕВОЙ длительностью - это конец маршрута. Направление DIR_STOP при
 * ненулевой длительности означает "стоять на месте", а не конец.
 *
 * Прежняя версия проверяла конец по route[step_no].ticks, то есть по исходной
 * константе, а не по остатку. На шаге ожидания остаток уходил в минус и
 * обнулялся в 255, прогон залипал, и телеметрия переставала зависеть от
 * маршрута - два разных маршрута давали побайтово одинаковый результат.
 */
uint8_t demo_input(void)
{
    if (finished)
        return DIR_STOP;

    if (step_left == 0) {
        ++step_no;
        step_left = route[step_no].ticks;
        if (step_left == 0) {
            finished = 1;
            return DIR_STOP;
        }
    }

    ++demo_tick;
    --step_left;
    return route[step_no].dir;
}

uint8_t demo_finished(void)
{
    return finished;
}

/*
 * Одна строка растра: n байт по восемь точек, установленный бит светится.
 * В ANTIC F бит экрана и есть точка, поэтому байт кладётся как есть - раньше,
 * при двух битах на точку, его приходилось разворачивать вдвое.
 */
static void draw_bits(uint8_t y, const uint8_t *data, uint8_t n)
{
    uint8_t *p = SCREEN_ROW(y);
    uint8_t i;

    for (i = 0; i < n; ++i)
        p[i] = data[i];
}

void demo_telemetry(void)
{
    extern uint8_t score[3];
    uint8_t buf[DEMO_TELEMETRY_BYTES];
    uint8_t y, n;

    buf[0] = (uint8_t)(demo_tick >> 8);
    buf[1] = (uint8_t)demo_tick;
    buf[2] = score[0];
    buf[3] = score[1];
    buf[4] = score[2];
    buf[5] = man.x;
    buf[6] = man.y;

    n = 0;
    for (y = 0; y < H_MAX; ++y) {
        uint16_t m = coins[y];
        while (m) {                     /* сколько камней осталось */
            n = (uint8_t)(n + (m & 1u));
            m >>= 1;
        }
    }
    buf[7] = n;

    buf[8] = 0;
    buf[9] = 0;
    for (y = 0; y < MAX_BAGS; ++y) {
        if (bags[y].state == BAG_STANDING || bags[y].state == BAG_LOOSE)
            ++buf[8];
        else if (bags[y].state == BAG_GOLD)
            ++buf[9];
    }

    {
        extern uint8_t game_lives;
        buf[10] = (uint8_t)((bugs_active << 4) | (game_lives & 0x0Fu));
    }

    /* Первый живой враг: по его координатам и направлению видно, ходит он
     * или застрял, и на каком именно остатке. */
    buf[11] = buf[12] = buf[13] = 0xFF;
    for (y = 0; y < MAX_BUGS; ++y) {
        if (bugs[y].state == BUG_ALIVE) {
            buf[11] = bugs[y].x;
            buf[12] = bugs[y].y;
            buf[13] = bugs[y].dir;
            break;
        }
    }

    {
        extern uint8_t mis_n_fired, mis_n_blocked, mis_n_offscreen;
        buf[14] = mis_n_fired;
        buf[15] = (uint8_t)((mis_n_blocked << 4) | (mis_n_offscreen & 0x0Fu));
    }
    {
        extern uint8_t levels_done, game_level;
        buf[16] = (uint8_t)((levels_done << 4) | (game_level & 0x0Fu));
    }
    {
        extern uint8_t sfx_started, sfx_writes;
        buf[17] = sfx_started;
        buf[18] = sfx_writes;
    }
    {
        extern uint8_t bonus_state, bonus_eaten;
        buf[19] = (uint8_t)((bonus_state << 4) | (bonus_eaten & 0x0Fu));
    }

    draw_bits(DEMO_TELEMETRY_Y, buf, DEMO_TELEMETRY_BYTES);
}

