; screen.s - резервирование кадрового буфера и дисплей-листа.
;
; Оба блока живут в отдельных сегментах с фиксированными адресами (см.
; cfg/digger.cfg) и НЕ попадают в XEX - в файле они не нужны, а стартовый код
; cc65 обнуляет только сегмент BSS по умолчанию, поэтому чистятся вручную.
;
;   SCRBUF -> $9000, 8352 байта: три прогона ANTIC E, ни один не пересекает 4К
;              +$0010 строки   0..101 (4080 байт)
;              +$1000 строки 102..203 (4080 байт)
;              +$1FF0 16 байт дырки - буфер НЕ непрерывен
;              +$2000 строки 204..207 (160 байт)
;   DLIST  -> $B400, 256 байт:  дисплей-лист (220), не пересекает границу 1К

        .export _screen_buf
        .export _dlist
        .export _screen_rowlo, _screen_rowhi
        .export _background

        .segment "SCRBUF"
_screen_buf:
        .res    $20A0

        .segment "DLIST"
_dlist:
        .res    $0100

; Свободное ОЗУ за дисплей-листом. Сюда вынесено из BSS то, что не помещалось
; в MAIN и НЕ ТРЕБУЕТ обнуления - обе таблицы и матрицу фона код заполняет
; целиком сам, до первого чтения (screen_init и field_init).
        .segment "ROWTAB"
_screen_rowlo:
        .res    208
_screen_rowhi:
        .res    208
_background:
        .res    300             ; H_MAX * W_MAX слов: состояние клеток поля
