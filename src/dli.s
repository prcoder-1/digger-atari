; dli.s - ЦЕПОЧКА прерываний по строке дисплей-листа.
;
; Слот 0 - смена палитры на границе панели счёта и игрового поля. В ANTIC F
; оттенок задаётся регистром COLPF2 на всю строку растра сразу, поэтому разные
; цвета у панели и у поля возможны только так. Обратно палитру панели
; возвращать не нужно: вторая стадия кадрового прерывания ОС переписывает
; теневые ячейки COLOR1/COLOR2 в железо, а в них лежат краски панели, и
; к строке 0 следующего кадра они уже на месте.
;
; Слоты 1..N - горизонтальные позиции игроков 2 и 3, то есть врагов. Один
; игрок держит несколько врагов сразу: в буфере они лежат каждый на своих
; строках растра, а HPOS у игрока один, и его надо переставлять по ходу кадра.
;
; Слоты стоят по НЕПОДВИЖНОЙ сетке через DLI_GRID строк: биты в дисплей-листе
; ставятся один раз и больше не трогаются, поэтому число прерываний в кадре
; постоянно и порядковый счётчик слотов не может сбиться. Таблицу позиций
; заполняет src/pmgbug.c - по клетке сетки, а не по врагу.
;
; Слот всегда пишет ОБЕ позиции, даже если на этой строке меняется только
; одна: вызывающий кладёт в таблицы полное состояние на эту строку, и
; переписывание неизменившегося регистра ничего не стоит.
;
; ОБРАБОТЧИКА ДВА, и палитра переключает вектор на второй сама. Разводить их
; ветвлением внутри одного было бы проще, но ветвление стоит тактов ДО WSYNC,
; а там счёт идёт на такты: измерено, что от лишних двух десятков палитра
; съезжает на строку вниз. У обоих обработчиков пролог до WSYNC теперь
; одинаковый - пятнадцать-шестнадцать тактов, - поэтому фора DLI_LEAD у них
; общая.
;
; Порядковый номер слота и вектор возвращает к началу кадровое прерывание
; (dli_vbi ниже) - оно отложенное и идёт до строки 0.
;
; Краски и позиции приходят из Си таблицами, а не зашиты сюда константами:
; ca65 не читает hw.h, и вторая копия палитры в ассемблере разъехалась бы с
; первой.

        .export _dli_install, _dli_remove, _dli_vbi
        .export _dli_pf1, _dli_pf2
        .export _dli_h2, _dli_h3, _dli_p3

DLI_SLOTS = 23                          ; клеток сетки, см. DLI_GRID_N в hw.h

VDSLST  = $0200
NMIEN   = $D40E
NMIEN_VBI = $40                         ; только кадровое
NMIEN_DLI_VBI = $C0                     ; $80 строчное + $40 кадровое
WSYNC   = $D40A
COLPF1  = $D017
COLPF2  = $D018
COLPF3  = $D019
HPOSP2  = $D002
HPOSP3  = $D003

        .segment "ZEROPAGE"
dli_idx:     .res 1                     ; какой слот позиций сейчас

        .segment "DATA"
_dli_pf1:    .byte 0                    ; яркость рисунка поля
_dli_pf2:    .byte 0                    ; фон и оттенок поля
_dli_h2:     .res DLI_SLOTS             ; HPOS игрока 2 по слотам
_dli_h3:     .res DLI_SLOTS             ; HPOS игрока 3 по слотам
_dli_p3:     .res DLI_SLOTS             ; краска пятого игрока по слотам
old_dli:     .word 0                    ; прежний вектор, чтобы вернуть при выходе

        .segment "CODE"

; void dli_install(void)
_dli_install:
        lda     VDSLST
        sta     old_dli
        lda     VDSLST+1
        sta     old_dli+1
        lda     #<pal_dli
        ldx     #>pal_dli
        jsr     set_vector              ; выйдет с NMIEN = только кадровое
        lda     #NMIEN_DLI_VBI
        sta     NMIEN
        rts

; void dli_remove(void)
;
; Вектор возвращается на место, а строчное прерывание остаётся снятым: NMIEN
; после set_vector разрешает только кадровое.
_dli_remove:
        lda     old_dli
        ldx     old_dli+1
        ; далее по коду set_vector

; A = младший байт вектора, X = старший.
; NMIEN снимается на время записи двух байт, чтобы прерывание не пришло на
; середину пары - тот же приём, что и в vbi.s. Регистр только для записи,
; поэтому восстанавливается константой, а не чтением.
set_vector:
        pha
        lda     #0
        sta     NMIEN
        pla
        sta     VDSLST
        stx     VDSLST+1
        lda     #NMIEN_VBI
        sta     NMIEN
        rts

; void dli_vbi(void) - начало кадра: цепочка снова с палитры.
_dli_vbi:
        lda     #0
        sta     dli_idx
        lda     #<pal_dli
        sta     VDSLST
        lda     #>pal_dli
        sta     VDSLST+1
        rts

; Слот 0: палитра. Краски загружаются ДО синхронизации - после WSYNC счёт идёт
; на такты, следующая строка уже начинает выводиться, и на две записи времени
; в обрез. Пролог до WSYNC - шестнадцать тактов, под них и подобрана DLI_LEAD.
pal_dli:
        pha
        txa
        pha
        lda     _dli_pf2
        ldx     _dli_pf1
        sta     WSYNC
        sta     COLPF2
        stx     COLPF1

        lda     #<hpos_dli              ; дальше по кадру идут позиции врагов
        sta     VDSLST
        lda     #>hpos_dli
        sta     VDSLST+1

        pla
        tax
        pla
        rti

; Слоты 1..N: горизонтальные позиции врагов и краска пятого игрока. До WSYNC
; пятнадцать тактов, как у палитры; остальное читается уже после синхронизации -
; там ещё гасящий импульс, выборки картинки нет, и тактов хватает с запасом.
;
; COLPF3 пишется ПОСЛЕДНИМ, и это не случайность: позиции игроков нужны в самом
; начале строки, а вишенка, единственная фигура на COLPF3, стоит у правого края
; поля - к её точкам краска успевает при любом раскладе. Так добавка в восемь
; тактов не сдвигает то, что критично.
;
; Ветка вишенки зелёная, а ягоды красные, потому что граница между ними легла
; ровно на стык клеток сетки: клетка 0 держит строки растра 28..35, клетка 1 -
; 36..43, а в спрайте ветка кончается на строке 8. Одной краской на кадр две
; половины было бы не покрасить.
hpos_dli:
        pha
        txa
        pha
        ldx     dli_idx
        lda     _dli_h2,x
        sta     WSYNC
        sta     HPOSP2
        lda     _dli_h3,x
        sta     HPOSP3
        lda     _dli_p3,x
        sta     COLPF3
        inc     dli_idx
        pla
        tax
        pla
        rti
