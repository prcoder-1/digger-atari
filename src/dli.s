; dli.s - прерывание по строке дисплей-листа: смена палитры на границе
; панели счёта и игрового поля.
;
; В ANTIC F оттенок задаётся регистром COLPF2 на всю строку растра сразу,
; поэтому разные цвета у панели и у поля возможны только так. Бит DLI стоит на
; ПОСЛЕДНЕЙ строке панели (строка 27, см. build_dlist в screen.c): прерывание
; приходит в конце этой строки, и записи ложатся уже на строку 28 - первую
; строку поля.
;
; Обратно палитру панели возвращать не нужно: вторая стадия кадрового
; прерывания ОС переписывает теневые ячейки COLOR1/COLOR2 в железо, а в них
; лежат краски панели. К строке 0 следующего кадра они уже на месте.
;
; Краски приходят из Си двумя байтами, а не зашиты сюда константами: ca65 не
; читает hw.h, и вторая копия палитры в ассемблере разъехалась бы с первой.

        .export _dli_install, _dli_remove
        .export _dli_pf1, _dli_pf2

VDSLST  = $0200
NMIEN   = $D40E
NMIEN_VBI = $40                         ; только кадровое
NMIEN_DLI_VBI = $C0                     ; $80 строчное + $40 кадровое
WSYNC   = $D40A
COLPF1  = $D017
COLPF2  = $D018

        .segment "DATA"
_dli_pf1:    .byte 0                    ; яркость рисунка поля
_dli_pf2:    .byte 0                    ; фон и оттенок поля
old_dli:     .word 0                    ; прежний вектор, чтобы вернуть при выходе

        .segment "CODE"

; void dli_install(void)
_dli_install:
        lda     VDSLST
        sta     old_dli
        lda     VDSLST+1
        sta     old_dli+1
        lda     #<handler
        ldx     #>handler
        jsr     set_vector              ; выйдет с NMIEN = только кадровое
        lda     #NMIEN_DLI_VBI
        sta     NMIEN
        rts

; void dli_remove(void)
;
; Вектор возвращается на место, а строчное прерывание остаётся снятым: NMIEN
; после set_vector разрешает только кадровое.
_dli_remove:
        lda     old_dli
        ldx     old_dli+1
        ; далее по коду set_vector

; A = младший байт вектора, X = старший.
; NMIEN снимается на время записи двух байт, чтобы прерывание не пришло на
; середину пары - тот же приём, что и в vbi.s. Регистр только для записи,
; поэтому восстанавливается константой, а не чтением.
set_vector:
        pha
        lda     #0
        sta     NMIEN
        pla
        sta     VDSLST
        stx     VDSLST+1
        lda     #NMIEN_VBI
        sta     NMIEN
        rts

; Обе краски загружаются ДО синхронизации: после WSYNC счёт идёт на такты,
; строка 28 уже начинает выводиться, и на две записи времени в обрез.
handler:
        pha
        txa
        pha
        lda     _dli_pf2
        ldx     _dli_pf1
        sta     WSYNC
        sta     COLPF2
        stx     COLPF1
        pla
        tax
        pla
        rti
