/*
 * bags.h - мешки с деньгами.
 *
 * Автомат состояний как в оригинале: стоит -> качается -> падает ->
 * разбивается -> золото -> исчез.
 *
 * Раскачка НЕ обязательна. Решает направление самого мешка: если он стоял
 * неподвижно и под ним подкопали - сначала качается, давая время убежать;
 * если его ЗАКАТИЛИ вбок на пустое место - проваливается сразу, без раскачки.
 * Поэтому у мешка есть поле dir, а проверка идёт только на границе клетки.
 *
 * Правило опоры взято из оригинала (Work/TB.C): мешок начинает падать, если
 * клетка под ним НЕ целиком нетронута, то есть если из неё выеден хоть один
 * укус. Маска 0xFDF - это все пять горизонтальных и все шесть вертикальных
 * бит; бит 5 в формате не используется, бит 13 "клетка цела" в проверку не
 * входит. Переносить сюда маску 0x66 из порта на БК нельзя: она выведена под
 * его модель 4/4, а у нас модель оригинала 5/6.
 */
#ifndef BAGS_H
#define BAGS_H

#include <stdint.h>
#include "hw.h"

#define MAX_BAGS    7u

#define BAG_NONE        0u
#define BAG_STANDING    1u
#define BAG_LOOSE       2u      /* качается перед падением */
#define BAG_FALLING     3u
#define BAG_BREAKING    4u
#define BAG_GOLD        5u      /* разбился, лежит золотом */

/* Столько тактов мешок качается, прежде чем упасть (как в порте на БК) */
#define LOOSE_WAIT      15u

typedef struct {
    uint8_t state;
    uint8_t x;          /* подшаги, как у Диггера */
    uint8_t y;          /* строки растра          */
    uint8_t dir;        /* куда мешок двигали в этот такт */
    uint8_t count;      /* счётчик текущей фазы   */
    uint8_t fell;       /* пролетел ли хоть клетку - от этого зависит, разобьётся ли */
} bag_t;

extern bag_t bags[MAX_BAGS];

/* Придавил ли падающий мешок Диггера */
uint8_t bags_hit_man(void);

void bags_init(uint8_t screen);
void bags_tick(void);

/* Пробует толкнуть мешок в клетке (x_log, y_log) в сторону dir.
 * Возвращает 1, если толкнуть удалось (или мешка там нет). */
uint8_t bags_push(uint8_t x_log, uint8_t y_log, uint8_t dir);

/* Забирает золото из разбившегося мешка, +500 очков. 1 - забрал. */
uint8_t bags_take_gold(uint8_t x_log, uint8_t y_log);

#endif /* BAGS_H */
