/*
 * field.h - состояние игрового поля и его отрисовка.
 *
 * Модель раскопа взята из оригинала для PC (Work/TG.C), а не из порта на БК:
 * она рассчитана ровно на выбранную геометрию 5 подшагов по X и 6 по Y.
 * Клетка фона - 16-битное слово:
 *
 *      биты 0..4    пять горизонтальных "укусов" (индекс = x_rem)
 *      биты 6..11   шесть вертикальных "укусов"  (индекс = y_rem)
 *      бит  13      клетка ещё цела
 *
 * Целая клетка = 0xFFFF; прокопка сбрасывает соответствующие биты.
 */
#ifndef FIELD_H
#define FIELD_H

#include <stdint.h>
#include "hw.h"

/* Символы карты уровня (совпадают с легендой оригинала) */
#define LEV_SPACE   0   /* целая земля            */
#define LEV_COIN    1   /* драгоценный камень     */
#define LEV_BAG     2   /* мешок с деньгами       */
#define LEV_HORIZ   3   /* прокопанный ход вбок   */
#define LEV_VERT    4   /* прокопанный ход вниз   */
#define LEV_BOTH    5   /* оба (гнездо врагов)    */

/* Маски прокопки, как в оригинале */
#define BG_INTACT       0x2000u         /* бит 13: клетка цела              */
#define BG_HORIZ_ALL    0x001Fu         /* биты 0..4                        */
#define BG_VERT_ALL     0x0FC0u         /* биты 6..11                       */
#define BG_DIG_VERT     0xD03Fu         /* &= для вертикального прохода     */
#define BG_DIG_HORIZ    0xDFE0u         /* &= для горизонтального прохода   */

/* Все укусы разом: клетка цела, когда установлены все одиннадцать. Бит 5 в
 * формате не используется, бит 13 "клетка цела" в маску не входит. */
#define BG_ANY_BITE     (BG_HORIZ_ALL | BG_VERT_ALL)    /* 0x0FDF */

extern uint16_t background[H_MAX][W_MAX];

/* Битовая маска оставшихся камней: бит x установлен - камень на месте.
 * Так проверка "все камни собраны" это десять сравнений с нулём. */
extern uint16_t coins[H_MAX];

/* Таблицы перевода графических координат в клетки и подшаги.
 * Делители 5 и 6 не степени двойки, поэтому только через таблицы. */
extern uint8_t x_log_tbl[80];   /* x_graph (подшаги по 2 px) -> клетка   */
extern uint8_t x_rem_tbl[80];   /* x_graph -> подшаг внутри клетки 0..4  */
extern uint8_t y_log_tbl[SCR_LINES];  /* строка растра -> клетка         */
extern uint8_t y_rem_tbl[SCR_LINES];  /* строка растра -> подшаг 0..5    */

void field_build_tables(void);

/* Символ карты уровня screen (0..7) в клетке (x, y) */
uint8_t level_sym(uint8_t screen, uint8_t x, uint8_t y);

/* Полная подготовка уровня: состояние фона, заливка землёй,
 * прокопка начальных ходов, вывод камней и мешков. */
void field_init(uint8_t screen);

/* Только перерисовка по текущему состоянию - для возрождения после гибели:
 * собранные камни не возвращаются, прокопанные ходы остаются. */
void field_redraw(uint8_t screen);

/* Гасит прямоугольник в пикселях (для прокопки). Обёртка над clear_px
 * из blit.s - на Си эта процедура неверно собиралась с оптимизацией. */
/* Закругляет торец хода в направлении dir; см. field.c */
void field_gnaw(uint8_t dir, uint8_t x_sub, uint8_t y);

void clear_px_at(uint8_t x_px, uint8_t y, uint8_t w_px, uint8_t h);

/* Забирает камень из клетки, если он там есть. Возвращает 1, если забрал. */
uint8_t field_take_coin(uint8_t x, uint8_t y);

/* Не осталось ли камней на поле */
uint8_t field_coins_left(void);

#endif /* FIELD_H */
