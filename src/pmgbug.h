/*
 * pmgbug.h - раскладка врагов по двум игрокам.
 *
 * Зовётся из src/bugs.c: раздача игроков в начале такта, а вывод и стирание
 * заливки - прямо из bug_draw/bug_erase, вплотную к выводу самой фигуры.
 * Почему нельзя отдельным проходом - в шапке src/pmgbug.c.
 */
#ifndef PMGBUG_H
#define PMGBUG_H

#include <stdint.h>

/* Раздать врагам игроков по высоте. Звать в начале bugs_tick(). */
void pmg_bugs_assign(void);

/* Убрать заливку врага; звать вместе со стиранием его фигуры. */
void pmg_bug_hide(uint8_t i);

/* Снять цвет с врагов под указанной клеткой - для сцены гибели, где
 * надгробие затирает фигуру врага-убийцы. */
void pmg_bugs_hide_at(uint8_t x, uint8_t y);

/* Положить заливку врага; звать вместе с выводом его фигуры. */
void pmg_bug_show(uint8_t i);

/*
 * Вишенка выводится четырьмя снарядами PMG как "пятый игрок": в кадровом
 * буфере её нет, поэтому и цвет у неё настоящий, и стереть её нечем.
 */
void pmg_bonus_show(uint8_t x_sub, uint8_t y);
void pmg_bonus_hide(uint8_t y);

#endif /* PMGBUG_H */
