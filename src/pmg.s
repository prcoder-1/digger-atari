; pmg.s - фигуры в аппаратных спрайтах (Player/Missile Graphics).
;
; Зачем: при одном бите на точку всё поле одного цвета, и фигуры сливаются с
; землёй. Аппаратный спрайт имеет собственный регистр цвета, независимый от
; режима поля, поэтому Диггеру и врагам можно вернуть краски.
;
; Игроки НЕ заменяют рисунок, а подкладывают под него цвет. Фигуры по-прежнему
; выводятся в кадровый буфер на всех 320 точках; игроки красят их изнутри, а по
; краю остаётся видна линия из кадрового буфера - в ней и держится чёткость.
; Ячейка игрока - такт цвета, то есть две точки, поэтому заливка идёт вдвое
; грубее рисунка, но её края спрятаны под ним.
;
; Положить игрока ПОД поле нельзя, хотя так было бы проще: измерено, что поле
; высокого разрешения участвует в разборе приоритетов целиком как COLPF2, и при
; приоритете поля над игроками ($04) зажжённые точки под игроком теряют яркость
; COLPF1 и превращаются в фон - рисунок просто стирается.
;
; Раскладка игроков:
;       0   корпус Диггера
;       1   клюв Диггера
;       2   враг
;       3   враг
;
; У Диггера два плана вместо трёх: колёса отдали цвет ради врагов (см.
; tools/spr2atari.py). Враги идут ОДНИМ планом на фигуру.
;
; Горизонтальную позицию игроков 2 и 3 ставит НЕ этот модуль, а цепочка
; прерываний по строке (src/dli.s): один игрок держит несколько врагов сразу,
; потому что в буфере они лежат каждый на своих строках растра, а вот HPOS у
; игрока один, и его приходится переставлять по ходу кадра. Раскладку слотов
; считает src/pmgbug.c.
;
; Раскладка буфера при однострочном разрешении (2 КБ с выравниванием на 2 КБ):
;   +$300  снаряды        (не используются)
;   +$400  игрок 0
;   +$500  игрок 1
;   +$600  игрок 2
;   +$700  игрок 3
; Внутри каждой области байт с индексом N выводится на строку растра N.

        .export _pmg_init, _pmg_show, _pmg_hide, _pmg_clear
        .export _pmg_band, _pmg_sizes
        .export _pmg_bug_put
        .export _pmg_hpos, _pmg_y, _pmg_s0, _pmg_s1
        .export _pmg_by, _pmg_bs, _pmg_bpl, _pmg_bmask
        .export _pmg_blo, _pmg_bhi

        .import _pm_buf

PM_P0   = $0400
PM_P1   = $0500
PM_P2   = $0600
PM_P3   = $0700
PMG_H   = 15                    ; высота спрайта в строках растра

; Смещение строки растра картинки в буфере игрока. ИЗМЕРЕНО, а не взято из
; описания: в буфер клался сплошной блок из пятнадцати байт по известному
; индексу и снимался кадр. Блок, записанный по смещениям 206..220, лёг на
; строки окна 198..212, то есть смещение = строка окна + 8. Картинка
; начинается со строки окна 24 (столько пустых строк в начале дисплей-листа),
; поэтому смещение = строка растра + 32.
;
; Верхняя граница проверена: 207 + 32 + 14 = 253, в область игрока (256 байт)
; спрайт помещается целиком и на начало не заворачивается.
PMG_Y_OFS = 32

PMBASE  = $D407
HPOSP0  = $D000
HPOSP1  = $D001
HPOSP2  = $D002
HPOSP3  = $D003
HPOSM0  = $D004
HPOSM1  = $D005
HPOSM2  = $D006
HPOSM3  = $D007
SIZEP0  = $D008
SIZEP1  = $D009
SIZEP2  = $D00A
SIZEP3  = $D00B
SIZEM   = $D00C
GRACTL  = $D01D
GPRIOR  = $026F                 ; теневая ячейка PRIOR

; Значение PRIOR: какой приоритет у игроков относительно поля. Задаётся при
; сборке (ca65 -DGPRIOR_VAL=...), чтобы перебирать варианты измерением, а не
; гадать по описанию: разбор приоритетов у GTIA в режимах высокого разрешения
; устроен особо.
.ifndef GPRIOR_VAL
GPRIOR_VAL = $01
.endif

        .segment "ZEROPAGE"
_pmg_hpos: .res 1               ; Диггер: позиция в тактах цвета
_pmg_y:  .res 1                 ; Диггер: строка растра
_pmg_s0: .res 2                 ; данные плана 0 (корпус)
_pmg_s1: .res 2                 ; данные плана 1 (клюв)
_pmg_by: .res 1                 ; враг: строка растра
_pmg_bs: .res 2                 ; враг: данные плана
_pmg_bpl: .res 1                ; враг: область игрока, 6 или 7
_pmg_bmask: .res 1              ; враг: маска видимой части заливки
_pmg_blo: .res 1                ; враг: первая выводимая строка плана
_pmg_bhi: .res 1                ; враг: последняя выводимая строка плана
pm_prev: .res 1                 ; где спрайт Диггера стоял в прошлый раз
pm_dst0: .res 2                 ; адрес строки в области игрока 0
pm_dst1: .res 2                 ; то же для игрока 1
bug_dst: .res 2                 ; адрес строки в области игрока врага

        .segment "CODE"

; ---------------------------------------------------------------------------
; pmg_init - чистит буфер, включает вывод игроков.
;
; Вызывать ДО screen_init: тот включает выборку игроков в DMACTL, и к этому
; моменту PMBASE уже должен указывать на очищенный буфер, иначе ANTIC успеет
; вывести мусор.
; ---------------------------------------------------------------------------
_pmg_init:
        lda     #>_pm_buf
        sta     PMBASE

        lda     #0
        ldx     #0
pi_clr: sta     _pm_buf+$300,x
        sta     _pm_buf+$400,x
        sta     _pm_buf+$500,x
        sta     _pm_buf+$600,x
        sta     _pm_buf+$700,x
        inx
        bne     pi_clr

        sta     SIZEP0                  ; обычный размер: 8 тактов цвета
        sta     SIZEP1
        sta     SIZEP2
        sta     SIZEP3
        sta     HPOSP2                  ; врагов ещё нет: увести за край
        sta     HPOSP3
        sta     pm_prev                 ; первое стирание попадёт выше картинки

        sta     SIZEM                   ; снаряды обычной ширины: 2 такта
        lda     #$03                    ; выборка игроков и снарядов
        sta     GRACTL
        ; Бит $10 сводит четыре снаряда в "пятого игрока" с краской COLPF3.
        ; Ею красится вишенка - единственный игрок, которого нет в кадровом
        ; буфере, см. COL_CHERRY в src/hw.h.
        lda     #GPRIOR_VAL|$10
        sta     GPRIOR
        rts

; ---------------------------------------------------------------------------
; pmg_clear - снимает с экрана ВСЮ спрайтовую графику: обе области Диггера,
; обе области врагов, снаряды-вишенку, и уводит все позиции за левый край.
;
; Нужно при смене уровня. Заливки врагов и вишенку там снимают поимённо
; (bugs_init, pmg_bonus_hide), а заливка Диггера оставалась: pmg_show гасит
; прежнее место сам, но только когда Диггера СНОВА рисуют, а между уровнями
; этого не происходит. Его краска так и висела в буфере игрока и всплывала на
; новом уровне в произвольном месте - там, где он стоял в конце прошлого.
;
; pm_prev обнуляется вместе с буфером: следующее стирание попадёт на строку 0,
; то есть выше картинки, и вреда не сделает - тот же приём, что в pmg_init.
; ---------------------------------------------------------------------------
_pmg_clear:
        lda     #0
        ldx     #0
pc_clr: sta     _pm_buf+$300,x          ; снаряды (вишенка)
        sta     _pm_buf+$400,x          ; Диггер: корпус
        sta     _pm_buf+$500,x          ; Диггер: клюв
        sta     _pm_buf+$600,x          ; враги: первый игрок
        sta     _pm_buf+$700,x          ; враги: второй игрок
        inx
        bne     pc_clr

        sta     HPOSP0
        sta     HPOSP1
        sta     HPOSP2
        sta     HPOSP3
        sta     HPOSM0
        sta     HPOSM1
        sta     HPOSM2
        sta     HPOSM3
        sta     pm_prev
        rts

; ---------------------------------------------------------------------------
; pmg_band - красит прямоугольник таблички GAME OVER.
;
; Зачем аппаратными спрайтами. В кадровом буфере цвета нет вовсе: оттенок на всю
; строку задаёт COLPF2, и покрасить им один прямоугольник нельзя - пришлось бы
; менять регистр посреди строки. А игрок позиционируется по горизонтали, и его
; краска ложится ровно куда надо.
;
; Ширины хватает за счёт растяжения: игрок обычной ширины покрывает 16 точек, а
; табличка 128. Поэтому обоим ставится УЧЕТВЕРЁННАЯ ширина (SIZEP = 3): бит
; начинает покрывать 4 такта цвета, то есть 8 точек, и игрок целиком - 64.
; Двоих ровно хватает на 128 точек, под которые и подогнана табличка.
;
; Что при этом видно, следует из правила, измеренного для этого режима
; (doc/graphics.md): где точка поля ПОГАШЕНА, виден игрок целиком - это фон
; таблички; где ЗАЖЖЕНА, игрок отдаёт только оттенок, а яркость приходит из
; COLPF1 - это рамка и буквы. Поэтому фон выходит тёмно-красным, а буквы
; светло-красными, и читаются они по-прежнему.
;
; Занимать игроков можно смело: игра кончилась, Диггер убран, враги сняты.
; Восстанавливает всё game_start при перезапуске.
;
; Вход: _pmg_by - первая строка растра, _pmg_bhi - сколько строк.
; ---------------------------------------------------------------------------
; Левый край таблички приходит из Си в _pmg_hpos - там же, где его считает
; PMG_HPOS. Держать это число ещё и здесь нельзя: разъедется.
;
; Игроков ровно ДВА, и это не случайность. Третий пробовали - его позицию
; перебивает цепочка прерываний по строке: та каждые восемь строк пишет HPOSP2
; из таблицы позиций врагов. Замер показал, что игрок уезжает то на тридцать
; тактов вправо, то к левому краю, и ни заморозка цепочки, ни заполнение
; таблицы нужным значением этого не вылечили. Поэтому табличка сделана такой,
; чтобы хватило двоих: 2 x 64 точки = 128, надпись в две строки по четыре знака.
BAND_STEP  = 32                 ; учетверённый игрок покрывает 32 такта

_pmg_band:
        lda     #3                      ; учетверённая ширина
        sta     SIZEP0
        sta     SIZEP1

        lda     _pmg_hpos
        sta     HPOSP0
        clc
        adc     #BAND_STEP
        sta     HPOSP1

        lda     _pmg_by
        clc
        adc     #PMG_Y_OFS
        tay                             ; Y - смещение в области игрока
        ldx     _pmg_bhi                ; счётчик строк
        lda     #$FF
pb_lp:  sta     _pm_buf+PM_P0,y
        sta     _pm_buf+PM_P1,y
        iny
        dex
        bne     pb_lp
        rts

; ---------------------------------------------------------------------------
; pmg_sizes - вернуть всем игрокам обычную ширину после таблички.
; ---------------------------------------------------------------------------
_pmg_sizes:
        lda     #0
        sta     SIZEP0
        sta     SIZEP1
        sta     SIZEP2
        sta     SIZEP3
        rts

; ---------------------------------------------------------------------------
; pmg_erase - гасит 15 байт там, где Диггер стоял в прошлый раз.
; ---------------------------------------------------------------------------
pmg_erase:
        ldy     pm_prev
        ldx     #PMG_H
        lda     #0
pe_lp:  sta     _pm_buf+PM_P0,y
        sta     _pm_buf+PM_P1,y
        iny
        dex
        bne     pe_lp
        rts

; ---------------------------------------------------------------------------
; pmg_show - переносит Диггера в позицию (_pmg_hpos тактов, _pmg_y строк).
; ---------------------------------------------------------------------------
; Оба плана копируются одним индексом Y: источник читается через (_pmg_sN),y,
; приёмник пишется через (pm_dstN),y. Адреса приёмников считаются один раз на
; вызов, и указатели вызывающего остаются нетронутыми. Области игроков
; отстоят ровно на страницу, поэтому второй адрес - это первый со старшим
; байтом на единицу больше.
_pmg_show:
        jsr     pmg_erase

        lda     _pmg_y
        clc
        adc     #PMG_Y_OFS
        sta     pm_prev

        clc
        adc     #<(_pm_buf+PM_P0)
        sta     pm_dst0
        lda     #>(_pm_buf+PM_P0)
        adc     #0
        sta     pm_dst0+1
        lda     pm_dst0                 ; области игроков идут по странице
        sta     pm_dst1
        lda     pm_dst0+1
        clc
        adc     #1
        sta     pm_dst1+1

        ldy     #PMG_H-1
ps_lp:  lda     (_pmg_s0),y
        sta     (pm_dst0),y
        lda     (_pmg_s1),y
        sta     (pm_dst1),y
        dey
        bpl     ps_lp

        lda     _pmg_hpos               ; позицию считает Си, см. pmg.h
        sta     HPOSP0
        sta     HPOSP1
        rts

; ---------------------------------------------------------------------------
; pmg_hide - убирает Диггера с экрана (сцена гибели рисует надгробие в поле).
; ---------------------------------------------------------------------------
_pmg_hide:
        jsr     pmg_erase
        lda     #0
        sta     HPOSP0
        sta     HPOSP1
        rts

; ---------------------------------------------------------------------------
; pmg_bug_put - кладёт 15 байт плана врага в область игрока _pmg_bpl (6 или 7)
; на строку растра _pmg_by. Горизонтальную позицию ставит прерывание.
; ---------------------------------------------------------------------------
; Младший байт адреса области нулевой (буфер выровнен на 2 КБ), поэтому
; смещение в области и есть младший байт приёмника.
_pmg_bug_put:
        lda     _pmg_by
        clc
        adc     #PMG_Y_OFS
        sta     bug_dst
        lda     #>_pm_buf
        clc
        adc     _pmg_bpl
        sta     bug_dst+1

; Выводятся строки _pmg_blo.._pmg_bhi включительно, а не все пятнадцать.
; Обрезка по СТРОКАМ нужна для очереди врагов: сосед в том же столбце закрывает
; собой не всю фигуру, а только перекрывшиеся строки, и гасить из-за него всю
; заливку - значит терять цвет у всех, кроме последнего в очереди.
;
; Условие выхода стоит ПОСЛЕ записи и сравнивает до уменьшения: иначе при
; _pmg_blo = 0 счётчик уходит в $FF и цикл не кончается никогда.
        ldy     _pmg_bhi
bp_lp:  lda     (_pmg_bs),y
        and     _pmg_bmask
        sta     (bug_dst),y
        cpy     _pmg_blo
        beq     bp_end
        dey
        bpl     bp_lp
bp_end: rts
