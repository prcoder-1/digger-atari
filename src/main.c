/*
 * Оттенок поля по уровню.
 *
 * Менять можно ровно одно число. В режиме высокого разрешения COLPF2 задаёт И
 * фон, И оттенок зажжённых точек, а яркость рисунка приходит из COLPF1 - это
 * измерено и записано в doc/graphics.md. Значит "другой цвет при той же
 * яркости" - это смена СТАРШЕГО полубайта COLPF2; младший (яркость фона)
 * остаётся как был, иначе поплывёт читаемость.
 *
 * Уровень 1 остаётся янтарным, как раньше. Цикл в восемь - тот же период, что
 * у самих карт: после восьмого уровня крутятся пятый..восьмой.
 *
 * ОТТЕНКИ ВЫБРАНЫ НЕ НА ГЛАЗ. Фигуры красятся аппаратными спрайтами, и их цвет
 * от уровня НЕ зависит: враги и клюв это оттенок C при яркости COLPF1
 * (#528408 на экране), корпус Диггера - оттенок 3 (#9c525a). Если поле взять
 * того же оттенка, фигура сливается с землёй - именно так пропадали враги на
 * зелёном поле.
 *
 * Померены все шестнадцать оттенков; в скобках худшее из двух расстояний до
 * цветов фигур (сумма по каналам):
 *
 *   годны:   1 (82), 5 (99), 6 (140), 9 (174), 7 (190), 8 (190)
 *   нельзя:  C (0 - ровно цвет врага), 3 (0 - ровно цвет Диггера),
 *            2 (24), D (42), B (49), 4 (58), E (66)
 *
 * Оттенок A (115) по числам проходил, но на снимке поле выходит откровенно
 * ЗЕЛЁНЫМ, и враги на нём теряются - число обмануло, решил глаз. Оттенок F
 * даёт на экране тот же цвет, что 1, и отдельной строки не стоит. Оттенок 0
 * (91) тоже годился бы, но это СЕРЫЙ - поле выходит бесцветным, и он убран по
 * просьбе: нужны только цветные.
 *
 * Порядок первых пяти задан явно (янтарный, пурпурный, синий, фиолетовый,
 * сине-зелёный); шестому достаётся последний неиспользованный годный оттенок,
 * а седьмой и восьмой повторяют первый и второй - безопасных всего шесть на
 * восемь уровней. Повторы стоят через шесть уровней от своих двойников, так
 * что соседние нигде не совпадают.
 *
 * Набор смещён в синие и фиолетовые: зелёные и красные заняты фигурами.
 * Захочется зелёный уровень - сперва менять цвет врагов.
 */
static const uint8_t level_hue[8] = {
    0x1,        /* 1 - янтарный        */
    0x5,        /* 2 - пурпурный       */
    0x8,        /* 3 - синий           */
    0x6,        /* 4 - фиолетовый      */
    0x9,        /* 5 - сине-зелёный    */
    0x7,        /* 6 - сине-фиолетовый */
    0x1,        /* 7 - янтарный СВЕТЛЫЙ  */
    0x5,        /* 8 - пурпурный СВЕТЛЫЙ */
};

/*
 * Яркость рисунка поля по уровню - вторая ось, чтобы восемь уровней были
 * разными БЕЗ повторов: годных оттенков всего шесть.
 *
 * Меняется именно COLPF1, то есть яркость зажжённых точек - это и есть цвет
 * земли. Фон (младший полубайт COLPF2) у всех уровней один: измерено, что при
 * яркости 8 земля выходит #946321, при 12 - #d6a56b, а фон в обоих случаях
 * #421000. Земля при этом отличается разительно, тёмно-коричневая против
 * песочной.
 *
 * Читаемость фигур от этого не страдает, а слегка выигрывает: расстояние от
 * земли до цвета врага при яркости 8 равно 124, при 12 - 132. Проверено и
 * глазами на увеличении.
 */
static const uint8_t level_lum[8] = { 8u, 8u, 8u, 8u, 8u, 8u, 12u, 12u };

#define FIELD_LUM   (COL_FIELD_PF2 & 0x0Fu)     /* яркость фона, обычная  */
#define BONUS_LUM   (COL_BONUS_PF2 & 0x0Fu)     /* она же в бонус-режиме  */

/*
 * Насколько бонус-режим поднимает яркость. Раньше обе яркости были зашиты
 * числами (рисунок 8 -> 14, фон 2 -> 6), но теперь у уровня своя яркость
 * рисунка, и прибавку надо считать ОТ НЕЁ - иначе на светлом уровне мигание
 * пропало бы.
 *
 * Потолок 14: младший бит яркости отбрасывается железом, 15 и 14 - одно и то
 * же. Светлый уровень поэтому мигает слабее (12 -> 14), но мигание держится
 * больше на фоне: тот прыгает с 2 на 6, а это заметно куда сильнее.
 */
#define BONUS_ADD_PF1   6u
#define BONUS_MAX_PF1   14u

static void field_palette(uint8_t bright)
{
    uint8_t i = (uint8_t)((game_level - 1u) & 7u);
    uint8_t hue = level_hue[i];
    uint8_t lum = level_lum[i];

    if (bright) {
        lum = (uint8_t)(lum + BONUS_ADD_PF1);
        if (lum > BONUS_MAX_PF1)
            lum = BONUS_MAX_PF1;
    }

    /* У COLPF1 оттенка нет вовсе: в этом режиме от него берётся только
     * яркость, поэтому старший полубайт нулевой. */
    dli_pf1 = ATARI_COLOR(0x0, lum);
    dli_pf2 = (uint8_t)((hue << 4) | (bright ? BONUS_LUM : FIELD_LUM));
}

