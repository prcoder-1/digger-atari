/*
 * pmgbug.c - враги в аппаратных спрайтах.
 *
 * Игроков четыре, живых врагов до пяти, а Диггер занимает двоих. Врагам
 * достаются игроки 2 и 3, и каждый держит НЕСКОЛЬКО врагов сразу: в буфере
 * игрока байт с индексом N выводится на строку растра N, так что фигуры на
 * разных высотах друг другу не мешают.
 *
 * Мешает другое: горизонтальная позиция у игрока одна на весь кадр. Её
 * переставляет прерывание по строке (src/dli.s).
 *
 * Игроки делятся НЕ по виду врага. В оригинале для PC и Ноббин, и Хоббин
 * зелёные - различаются формой, а не цветом, - поэтому краска у обоих игроков
 * одна, и второй нужен ровно затем, чтобы развести двух врагов, стоящих на
 * одной высоте. Каждый враг садится на того игрока, который к его строке уже
 * освободился; если заняты оба, враг остаётся в цвете поля.
 *
 * ЧЕТЫРЕ ПРАВИЛА, БЕЗ КОТОРЫХ НА ЭКРАНЕ ПОЯВЛЯЮТСЯ ПРИЗРАКИ.
 *
 * Призрак выглядит так: заливка врага возникает в стороне от него самого, на
 * той же высоте, на долю секунды. Признак в снимке однозначный - у заливки
 * ЧИСТЫЙ цвет игрока (#528408) вместо пастельного (#BDEF7B): под ней нет
 * зажжённых точек поля. Оба правила выведены отладкой, и оба нарушались.
 *
 * 1. СЕТКА ПРЕРЫВАНИЙ НЕПОДВИЖНА. Соблазнительно ставить бит DLI на строку
 *    каждого врага и двигать вместе с ним. Так нельзя: слоты нумеруются
 *    порядковым счётчиком, и стоит числу или порядку прерываний измениться,
 *    пока растр уже идёт по картинке, как счёт сбивается на единицу и дальше
 *    КАЖДЫЙ враг получает позицию соседа. Плюс в промежутке "старый бит снят,
 *    новый не поставлен" врагу не достаётся позиции вовсе. Поэтому биты стоят
 *    неподвижной сеткой через DLI_GRID строк (build_dlist в screen.c), число
 *    прерываний в кадре постоянно, а здесь заполняется только ТАБЛИЦА позиций -
 *    по клетке сетки, а не по врагу.
 *
 * 2. ЗАЛИВКА ДВИГАЕТСЯ ВМЕСТЕ С РИСУНКОМ. Кадровый буфер не двойной, враги
 *    перерисовываются посреди кадра, и растр это видит. Если заливку класть
 *    отдельным проходом - хоть в конце такта, хоть в гасящем импульсе, - между
 *    перерисовкой врага и переносом его заливки остаётся окно, и всё это окно
 *    враг выводится с заливкой от прошлой позиции. Отставание ровно на подшаг,
 *    то есть на 4 точки, и выглядит оно как зелёный двойник сбоку. Поэтому
 *    pmg_bug_show/pmg_bug_hide зовутся ИЗ bug_draw/bug_erase, вплотную к
 *    выводу самой фигуры: тогда рисунок и заливка рвутся в одном и том же
 *    месте кадра, то есть согласованно.
 *
 * 3. ЗАЛИВКА ПОЯВЛЯЕТСЯ ПОСЛЕДНЕЙ И УБИРАЕТСЯ ПЕРВОЙ. Растр идёт по картинке
 *    всё время, и в зазор между "стёрли рисунок" и "сняли заливку" он успевает
 *    пройти по врагу. Если снимать заливку второй, в этот зазор видна заливка
 *    БЕЗ фигуры - тот самый зелёный силуэт. Поэтому bug_erase снимает заливку
 *    ДО clear_px, а bug_draw кладёт её ПОСЛЕ blit_mask: в зазоре тогда видна
 *    фигура без цвета, чего почти не заметно. Зазор крошечный, сотни тактов, -
 *    но такт игры идёт от кадрового импульса, фаза постоянна, и врагу на
 *    "несчастливой" высоте не везло каждый раз.
 *
 * 4. ВРАГИ РИСУЮТСЯ ПОСЛЕДНИМИ И ВСЕ РАЗОМ (bugs_draw_all в bugs.c). Кто
 *    обрабатывается позже - сосед по списку, снаряд, - тот своим стиранием
 *    выскабливает уже нарисованного, а заливка остаётся. Отсюда же обрезка
 *    заливки по соседу в pmg_bug_show и снятие цвета из pmg_bugs_hide_at -
 *    им пользуются надгробие на сцене гибели и вишенка, которая ложится на
 *    гнездо поверх врагов.
 *
 * Отсюда требование к зазору между врагами на одном игроке: позиция из таблицы
 * вступает в силу на ближайшей клетке сетки ВЫШЕ врага, то есть до DLI_GRID
 * строк раньше его верха, и на эти строки не должен попадать предыдущий враг.
 */
#include "pmgbug.h"
#include "bugs.h"
#include "pmg.h"
#include "dli.h"
#include "game.h"
#include "hw.h"

/*
 * Статические данные модуля уезжают в ОЗУ под ПЗУ: MAIN забит под завязку.
 * Обнуляет этот сегмент game_clear_hi_bss() первым делом в main - стартовый
 * код cc65 сюда не дотягивается, он чистит только сегмент BSS.
 */
#ifdef __CC65__
#pragma bss-name (push, "BSS_HI")
#endif


/* Вишенка: план для четырёх снарядов, порядок бит у них свой */
extern const uint8_t pm_z1_0[];

/* Заливка врагов: по одному плану на кадр, см. tools/spr2atari.py */
extern const uint8_t pm_m0_0[], pm_m1_0[], pm_m2_0[];
extern const uint8_t pm_c0_0[], pm_c1_0[], pm_c2_0[];
extern const uint8_t pm_a0_0[], pm_a1_0[], pm_a2_0[];

/* [облик: 0 Ноббин, 1 Хоббин вправо, 2 Хоббин влево][фаза] - как bug_spr */
static const uint8_t *const bug_pm[3][3] = {
    { pm_m0_0, pm_m1_0, pm_m2_0 },
    { pm_c0_0, pm_c1_0, pm_c2_0 },
    { pm_a0_0, pm_a1_0, pm_a2_0 },
};

/*
 * Два игрока на врагов: два других держат корпус и клюв Диггера.
 *
 * Третьего слота ЗДЕСЬ НЕ БУДЕТ, и это упирается в железо. Освободить игрока
 * можно было только одним способом - увести клюв на пятого игрока (четыре
 * снаряда с общей краской COLPF3). Проверено сборкой: не годится. Краска
 * пятого игрока это COLPF3, то есть регистр ПОЛЯ, и на зажжённой точке она с
 * цветом поля СМЕШИВАЕТСЯ, а не заменяет его: оттенок поля 1 плюс зелёный C
 * дают лиловое пятно по всей фигуре. У обычного игрока правило другое, там
 * выходит пастельный оттенок своей краски.
 *
 * Вишенка на пятом игроке работает именно потому, что под ней кадровый буфер
 * ПУСТ (см. doc/graphics.md). Клюв - часть рисунка Диггера, и пустым его не
 * сделать, не огрубив форму до ячейки в две точки.
 *
 * Следствие: трое врагов, вставших в ОДИН РЯД, по полосам растра не
 * разводятся - они на одной высоте, - и третьему цвет не достаётся.
 */
static const uint8_t bug_player[2] = { PMG_PL_BUG0, PMG_PL_BUG1 };

/* Пустой блок: стирание - это тот же вывод плана, только нулевого */
static const uint8_t pm_blank[SPRITE_H] = { 0 };

/*
 * Что остаётся от заливки, когда сосед стоит в d подшагах. Индекс - смещение
 * соседа плюс SPRITE_W_SUB-1, то есть от -3 подшагов (сосед слева, закрывает
 * левые шесть ячеек) до +3 (справа). В середине ноль: совпали - закрыт весь.
 */
static const uint8_t clip_tbl[2u * SPRITE_W_SUB - 1u] = {
    0x3Fu, 0x0Fu, 0x03u, 0x00u, 0xC0u, 0xF0u, 0xFCu
};

/*
 * Зазор между врагами на ОДНОМ игроке. Считается из окон в клетках сетки:
 * враг занимает три клетки, значит номера клеток у соседей должны отличаться
 * минимум на три, а это 24 строки растра. Плюс по подшагу в 3 строки на
 * каждого - они могут шагнуть навстречу уже после раздачи. Итого 30, взято 32
 * с запасом.
 */
#ifndef BUG_GAP                 /* переопределяется в опытах со сборкой */
#define BUG_GAP     32u
#endif




/* Кому какой игрок назначен: 0 - без цвета */
static uint8_t bug_pl[MAX_BUGS];

/* С каким игроком и на какой строке враг лежит в буфере СЕЙЧАС. Стирать надо
 * по этим числам, а не по текущим: назначение могло смениться. */
static uint8_t drawn_pl[MAX_BUGS];
static uint8_t drawn_y[MAX_BUGS];

/*
 * Раздача игроков: проход по живым врагам в порядке возрастания y, каждый
 * садится на первого свободного игрока. Свободен тот, чей прошлый враг
 * кончился достаточно высоко.
 *
 * Равные y разбираются по номеру врага: без этого двое в одном ходу на одной
 * строке считались бы за одного, и второй никогда не получал бы цвета - а это
 * ровно тот случай, ради которого второй игрок и заведён.
 */
void pmg_bugs_assign(void)
{
    uint8_t i, p, best, best_y, prev_y, prev_i, have_prev;
    uint8_t last_y[2], used[2];

    /* Заодно страховка: у мёртвого врага заливки быть не должно. Все пути
     * гибели зовут bug_erase, но цена проверки - пять сравнений в такт, а
     * забытое пятно висело бы до конца уровня. */
    for (i = 0; i < MAX_BUGS; ++i) {
        bug_pl[i] = 0;
        if (bugs[i].state != BUG_ALIVE)
            pmg_bug_hide(i);
    }

    used[0] = 0;
    used[1] = 0;
    last_y[0] = 0;
    last_y[1] = 0;
    prev_y = 0;
    prev_i = 0;
    have_prev = 0;

    for (;;) {
        best = MAX_BUGS;
        best_y = 0xFFu;
        for (i = 0; i < MAX_BUGS; ++i) {
            const bug_t *b = &bugs[i];
            if (b->state != BUG_ALIVE)
                continue;
            if (have_prev && (b->y < prev_y ||
                              (b->y == prev_y && i <= prev_i)))
                continue;
            if (best == MAX_BUGS || b->y < best_y) {
                best_y = b->y;
                best = i;
            }
        }
        if (best == MAX_BUGS)
            break;

        prev_y = best_y;
        prev_i = best;
        have_prev = 1;

        for (p = 0; p < 2u; ++p)
            if (!used[p] || (uint8_t)(best_y - last_y[p]) >= BUG_GAP)
                break;
        if (p == 2u)
            continue;               /* оба заняты - этот враг без цвета */

        used[p] = 1;
        last_y[p] = best_y;
        bug_pl[best] = bug_player[p];
    }

}

/*
 * Снимает цвет с врагов, попавших под указанную клетку. Нужно на сцене
 * гибели: надгробие вырастает на месте Диггера и стирает фигуру врага-убийцы,
 * а заливка его аппаратного спрайта осталась бы висеть зелёным блоком - врагов
 * в этой сцене никто уже не перерисовывает.
 */
void pmg_bugs_hide_at(uint8_t x, uint8_t y)
{
    uint8_t i;

    for (i = 0; i < MAX_BUGS; ++i) {
        if ((uint8_t)(bugs[i].x - x + SPRITE_W_SUB)
                < (uint8_t)(2u * SPRITE_W_SUB) &&
            (uint8_t)(bugs[i].y - y + SPRITE_H) < (uint8_t)(2u * SPRITE_H)) {
            pmg_bug_hide(i);
            bug_pl[i] = 0;
        }
    }
}

/* Убирает заливку врага оттуда, куда она была положена */
void pmg_bug_hide(uint8_t i)
{
    if (!drawn_pl[i])
        return;
    pmg_by = drawn_y[i];
    pmg_bpl = drawn_pl[i];
    pmg_bmask = 0xFFu;
    /* Стирается ВСЕГДА вся высота, даже если заливку выводили обрезанной по
     * строкам: лишнее гашение безвредно, а недостёртое - это призрак. */
    pmg_blo = 0;
    pmg_bhi = SPRITE_H - 1u;
    pmg_bs = pm_blank;
    pmg_bug_put();
    drawn_pl[i] = 0;
}

/*
 * Кладёт заливку врага и его горизонтальную позицию в клетки сетки, которые он
 * занимает. Клеток ровно три: пятнадцать строк спрайта при шаге сетки восемь
 * ложатся на три клетки.
 *
 * Клетку ВЫШЕ брать не надо, хотя соблазн есть: клетка g вступает в силу на
 * строке FIELD_Y_OFFSET + 8g, а она по построению не ниже верха фигуры -
 * позиция готова заранее. Лишняя клетка сверху только расширяет окно, и окна
 * соседей начинают перекрываться: тот, кого записали вторым, стирает позицию
 * первого, и первый выводится с чужой - это и был остаточный призрак.
 */
void pmg_bug_show(uint8_t i)
{
    const bug_t *b = &bugs[i];
    uint8_t p = bug_pl[i];
    uint8_t look, g, j, last, hpos;
    uint8_t clip = 0xFFu;
    uint8_t lo = 0, hi = SPRITE_H - 1u;  /* какие строки заливки остаются */
    uint8_t *tab;

    if (!p)
        return;

    /*
     * Заливка ОБРЕЗАЕТСЯ по той части, которую закрывает сосед. Спрайты
     * выводятся с ореолом, и сосед с бОльшим номером своей маской гасит уже
     * нарисованного: на закрытых точках рисунка не останется, а заливка без
     * рисунка - это чистый цвет игрока, зелёный блок.
     *
     * Раньше тут цвет снимался ЦЕЛИКОМ, при любом касании. Правило било по
     * самому обычному построению: враги в одном ходу подходят друг к другу
     * вплотную (bug_touches_other пускает их на три подшага), и в ряду цвет
     * оставался только у последнего по номеру, а если ему не досталось
     * игрока - то ни у кого. При этом закрыт у соседей лишь один подшаг из
     * четырёх, то есть терялось три четверти цвета ни за что.
     *
     * Ячейка игрока - две точки, подшаг - четыре, значит подшаг это две
     * ячейки, и обрезка ложится на биты байта заливки ровно: сосед справа на
     * d подшагов оставляет левые 2d ячеек, слева - правые. Габарит ТОЧНЫЙ,
     * без запаса на шаг навстречу: к моменту вывода все уже сходили.
     */
    for (j = (uint8_t)(i + 1u); j < MAX_BUGS; ++j) {
        const bug_t *o = &bugs[j];
        uint8_t d;
        if (o->state != BUG_ALIVE)
            continue;
        if ((uint8_t)(o->y - b->y + SPRITE_H) >= (uint8_t)(2u * SPRITE_H))
            continue;                   /* по высоте не пересекаются */
        d = (uint8_t)(o->x - b->x + SPRITE_W_SUB - 1u);
        if (d > 2u * SPRITE_W_SUB - 2u)
            continue;                   /* по ширине не пересекаются */
        /*
         * Сосед в ТОМ ЖЕ столбце - это очередь: враги идут гуськом по
         * коридору, один над другим. Маска обрезки горизонтальная, и на такого
         * соседа она даёт ноль (середина clip_tbl), то есть гасила заливку
         * ЦЕЛИКОМ. А закрыты на деле только перекрывшиеся строки - сосед стоит
         * выше или ниже и стирает своей маской лишь их. Из-за этого в очереди
         * цвет доставался последнему, а все передние шли в цвете поля; ровно
         * это и видно в игре.
         *
         * Поэтому здесь обрезка идёт ПО СТРОКАМ: вывод плана ограничивается
         * диапазоном lo..hi, см. _pmg_bug_put в src/pmg.s.
         */
        if (o->x == b->x) {
            if (o->y > b->y) {          /* сосед ниже - закрывает низ */
                uint8_t k = (uint8_t)(o->y - b->y - 1u);
                if (k < hi)
                    hi = k;
            } else if (o->y < b->y) {   /* сосед выше - закрывает верх */
                uint8_t k = (uint8_t)(SPRITE_H - (b->y - o->y));
                if (k > lo)
                    lo = k;
            } else {
                return;                 /* ровно друг на друге - закрыт весь */
            }
            continue;
        }

        /*
         * Сосед, у которого ЕСТЬ своя заливка, обрезки не требует. Смысл
         * обрезки - не оставить цвет там, где сосед стёр своей маской нашу
         * фигуру: заливка без фигуры это чистый зелёный блок. Но если сосед
         * сам покрашен, на том же месте стоит ЕГО фигура и ЕГО заливка, и
         * блока не выйдет - краска у врагов одна на всех.
         *
         * Без этого трое врагов, вставших в ряд бок о бок, теряли цвет почти
         * целиком: у переднего от заливки оставалось две ячейки из восьми,
         * то есть четыре точки, и на экране казалось, что покрашен один.
         */
        if (bug_pl[j])
            continue;

        clip &= clip_tbl[d];
    }
    if (!clip || lo > hi)
        return;                         /* закрыт целиком - цвета нет */

    /* Облик выбирается как в bug_draw: у Хоббина своя графика на сторону */
    if (b->kind != BUG_HOBBIN)
        look = 0;
    else
        look = (uint8_t)((b->dir == DIR_LEFT) ? 2u : 1u);

    /* Счётчик кадра растёт без границы, как и в bug_draw: остаток от трёх
     * берётся на месте, а не при увеличении. */
    pmg_by = b->y;
    pmg_bpl = p;
    pmg_bmask = clip;
    pmg_blo = lo;
    pmg_bhi = hi;
    pmg_bs = bug_pm[look][b->frame % 3u];
    pmg_bug_put();

    drawn_pl[i] = p;
    drawn_y[i] = b->y;

    hpos = PMG_HPOS(b->x);
    tab = (p == PMG_PL_BUG0) ? dli_h2 : dli_h3;

    g = (uint8_t)((b->y - FIELD_Y_OFFSET) / DLI_GRID);
    j = g;
    last = (uint8_t)(g + 2u);
    if (last >= DLI_GRID_N)
        last = DLI_GRID_N - 1u;
    for (; j <= last; ++j)
        tab[j] = hpos;
}

/*
 * ВИШЕНКА - ПЯТЫЙ ИГРОК.
 *
 * Четыре игрока разобраны: двое у Диггера, двое у врагов. Вишенке достаются
 * снаряды: бит $10 в PRIOR сводит все четыре в "пятого игрока" с общей
 * краской COLPF3 (pmg_init в src/pmg.s). Снаряд обычной ширины - два такта
 * цвета, то есть подшаг, и четыре подряд дают ровно ширину спрайта.
 *
 * Из кадрового буфера вишенка при этом ушла совсем, и это не побочность, а
 * условие цвета: у зажжённой точки поля яркость навязана из COLPF1, и любой
 * тёмный оттенок под ней выцвел бы в пастельный. Раз рисунка нет - краска
 * работает целиком, и бордовый остаётся бордовым. Заодно вишенку больше
 * некому стереть: враги ходят по кадровому буферу, а она не в нём.
 *
 * Данные снарядов лежат в области буфера со смещением $300, то есть на
 * "странице" 3 - той же арифметикой, что и области игроков 6 и 7, поэтому
 * кладёт их та же pmg_bug_put.
 */
#define PMG_PL_MISSILES 3u

void pmg_bonus_show(uint8_t x_sub, uint8_t y)
{
    uint8_t h = PMG_HPOS(x_sub);
    uint8_t g = (uint8_t)((y - FIELD_Y_OFFSET) / DLI_GRID);

    /*
     * Две краски на одну фигуру. Клетка сетки g держит восемь строк растра, а
     * в спрайте вишенки ветка кончается на восьмой строке - ровно на стыке
     * клеток. Значит верхняя клетка красится зелёным, следующая красной, и
     * ничего сверх уже имеющейся цепочки прерываний не нужно.
     *
     * Граница ЖЁСТКО связана с раскроем плана: в tools/spr2atari.py выше
     * границы в план идут только точки ветки, ниже - все. Сдвинете одно -
     * двигайте и другое.
     */
    dli_p3[g] = COL_CHERRY_STEM;
    dli_p3[g + 1u] = COL_CHERRY;


    pmg_by = y;
    pmg_bpl = PMG_PL_MISSILES;
    pmg_bmask = 0xFFu;
    pmg_blo = 0;
    pmg_bhi = SPRITE_H - 1u;
    pmg_bs = pm_z1_0;
    pmg_bug_put();

    GTIA_HPOSM0 = h;
    GTIA_HPOSM1 = (uint8_t)(h + 2u);
    GTIA_HPOSM2 = (uint8_t)(h + 4u);
    GTIA_HPOSM3 = (uint8_t)(h + 6u);
}

void pmg_bonus_hide(uint8_t y)
{
    pmg_by = y;
    pmg_bpl = PMG_PL_MISSILES;
    pmg_bmask = 0xFFu;
    pmg_blo = 0;
    pmg_bhi = SPRITE_H - 1u;
    pmg_bs = pm_blank;
    pmg_bug_put();

    GTIA_HPOSM0 = 0;
    GTIA_HPOSM1 = 0;
    GTIA_HPOSM2 = 0;
    GTIA_HPOSM3 = 0;
}

