/*
 * dli.h - цепочка прерываний по строке.
 *
 * Реализация в src/dli.s. Слот 0 - палитра: краски поля кладутся в
 * dli_pf1/dli_pf2 перед dli_install(), краски панели живут в теневых ячейках
 * ОС (OS_COLOR1/COLOR2). Дальше по кадру идут слоты с горизонтальными
 * позициями игроков 2 и 3 (враги), их заполняет src/pmgbug.c.
 */
#ifndef DLI_H
#define DLI_H

#include <stdint.h>

#define DLI_SLOTS   8           /* размер таблиц позиций, см. src/dli.s */

extern uint8_t dli_pf1;         /* яркость рисунка поля -> COLPF1 */
extern uint8_t dli_pf2;         /* фон и оттенок поля   -> COLPF2 */

/*
 * Полное состояние позиций на строку слота: слот пишет ОБА регистра, поэтому
 * в таблицу кладётся действующее значение для обоих игроков, а не только
 * изменившееся.
 */
extern uint8_t dli_h2[DLI_SLOTS];       /* HPOS игрока 2 (Ноббины) */
extern uint8_t dli_h3[DLI_SLOTS];       /* HPOS игрока 3 (Хоббины) */

/* Ставит вектор и разрешает строчное прерывание. Вызывать после того, как в
 * дисплей-листе выставлен бит DLI, и до включения ANTIC. */
void dli_install(void);

/* Возвращает прежний вектор и гасит строчное прерывание. */
void dli_remove(void);

#endif /* DLI_H */
