/*
 * compat.h - различия между cc65 и llvm-mos в одном месте.
 *
 * Порт собирается двумя компиляторами из одного исходника: cc65 (цель atarixl)
 * и llvm-mos. Ассемблер при этом не дублируется - файлы src со суффиксом .s переводятся
 * скриптом tools/ca65_to_mos.py, см. doc/llvm-mos.md.
 */
#ifndef COMPAT_H
#define COMPAT_H

/*
 * Соглашение о вызове. У cc65 __fastcall__ означает "первый аргумент в A/X";
 * у llvm-mos это и есть обычное соглашение - проверено по выводу компилятора:
 * score_add(0x1234) собирается в lda #$34 / ldx #$12 / jsr. Поэтому наши
 * ассемблерные точки входа работают в обеих сборках без правок, а само слово
 * достаточно убрать.
 */
#ifndef __CC65__
#define __fastcall__
#endif

#endif /* COMPAT_H */
