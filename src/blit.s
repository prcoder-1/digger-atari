; blit.s - вывод спрайтов в кадровый буфер ANTIC E.
;
; Параметры передаются через ячейки нулевой страницы, а не через стек cc65:
; это классический для cc65 приём, он снимает всю цену передачи аргументов.
;
; Модель вывода (как в оригинале для PC):
;       экран = (экран И маска) ИЛИ изображение
; Данные спрайта - пары (маска, изображение) подряд по строке, поэтому
; внутренний цикл читает оба байта монотонно растущим Y:
;
;       lda (bl_src),y   ; маска        5
;       iny              ;              2
;       and экран,x      ;              4
;       ora (bl_src),y   ; изображение  5
;       iny              ;              2
;       sta экран,x      ;              5
;       inx / cpx / bne  ;              7
;                        ; итого       30 тактов на байт
;
; Адрес строки экрана берётся из таблиц screen_rowlo/hi (буфер не непрерывен,
; см. screen.c) и подставляется в операнды команд. Самомодификация освобождает
; оба индексных регистра: X адресует байт назначения, Y - источник.
;
; Индексация ",x" (а не два отдельных абсолютных адреса) выбрана намеренно:
; строка экрана может пересекать границу страницы, и ",x" переносит сама.

        .export _bl_x, _bl_y, _bl_w, _bl_h, _bl_src
        .export _blit_mask, _blit_copy, _blit_clear, _blit_plain
        .export _cp_x, _cp_y, _cp_w, _cp_h, _clear_px

        .import _screen_rowlo, _screen_rowhi

        .segment "ZEROPAGE"
_bl_x:   .res 1                 ; байт экрана (0..39)
_bl_y:   .res 1                 ; первая строка растра (0..207)
_bl_w:   .res 1                 ; байт в строке
_bl_h:   .res 1                 ; строк
_bl_src: .res 2                 ; указатель на данные спрайта
bl_row:  .res 1                 ; текущая строка растра
bl_cnt:  .res 1                 ; сколько строк осталось

_cp_x:   .res 1                 ; clear_px: левый ПОДШАГ (полбайта)
_cp_y:   .res 1                 ; clear_px: первая строка растра
_cp_w:   .res 1                 ; clear_px: ширина в ПОДШАГАХ
_cp_h:   .res 1                 ; clear_px: высота в строках
cp_ptr:  .res 2                 ; указатель на текущую строку экрана
cp_x0:   .res 1                 ; первый байт
cp_x1:   .res 1                 ; последний байт
cp_lm:   .res 1                 ; маска гасимых пикселей в первом байте
cp_rm:   .res 1                 ; маска гасимых пикселей в последнем байте

        .segment "CODE"

; Подставляет адрес (строка bl_row + _bl_x) в операнды двух команд.
; Портит A и X. Это макрос, а не подпрограмма: jsr/rts стоили бы 12 тактов
; на каждую строку спрайта.
.macro  SET_ROW_ADDR  op1, op2
        ldx     bl_row
        lda     _screen_rowlo,x
        clc
        adc     _bl_x
        sta     op1+1
        sta     op2+1
        lda     _screen_rowhi,x
        adc     #0
        sta     op1+2
        sta     op2+2
.endmacro

; Общая для всех трёх процедур подготовка счётчиков строк
.macro  BLIT_SETUP
        lda     _bl_y
        sta     bl_row
        lda     _bl_h
        sta     bl_cnt
.endmacro

; ---------------------------------------------------------------------------
; blit_mask - вывод с маской: экран = (экран И маска) ИЛИ изображение
; ---------------------------------------------------------------------------
_blit_mask:
        BLIT_SETUP
        ldy     #0                     ; индекс источника, растёт монотонно
bm_row:
        SET_ROW_ADDR bm_and, bm_sta
        ldx     #0
bm_col:
        lda     (_bl_src),y            ; маска
        iny
bm_and: and     $FFFF,x
        ora     (_bl_src),y            ; изображение
        iny
bm_sta: sta     $FFFF,x
        inx
        cpx     _bl_w
        bne     bm_col
        inc     bl_row
        dec     bl_cnt
        bne     bm_row
        rts

; ---------------------------------------------------------------------------
; blit_copy - непрозрачный вывод, маска в данных пропускается.
; Для существ, идущих по уже прокопанному чёрному ходу.
; ---------------------------------------------------------------------------
_blit_copy:
        BLIT_SETUP
        ldy     #1                     ; изображение лежит вторым в паре
bc_row:
        SET_ROW_ADDR bc_sta, bc_sta
        ldx     #0
bc_col:
        lda     (_bl_src),y
        iny
        iny
bc_sta: sta     $FFFF,x
        inx
        cpx     _bl_w
        bne     bc_col
        inc     bl_row
        dec     bl_cnt
        bne     bc_row
        rts

; ---------------------------------------------------------------------------
; clear_px - гасит прямоугольник, заданный В ПОДШАГАХ по X (_cp_x, _cp_w) и
; в строках растра по Y (_cp_y, _cp_h). Края, не попавшие на границу байта,
; гасятся маской.
;
; Основной примитив прокопки: ход шириной 4 подшага из клетки в 5 и высотой
; 15 строк из 18 - именно неполнота и даёт разделители земли между клетками.
;
; Почему единица - подшаг, а не пиксель. В обоих режимах, между которыми
; выбирает порт, подшаг ровно вдвое короче байта: в ANTIC E байт это 4 пикселя
; при подшаге 2, в ANTIC F - 8 пикселей при подшаге 4. Поэтому в подшагах и
; арифметика байта, и обе маски одинаковы, а весь вызывающий код не зависит от
; числа бит на точку. В пикселях этого не выходит: при 320 точках координата
; правой клетки поля (288) уже не помещается в байт.
;
; На ассемблере эта процедура не ради скорости (хотя вызывается каждый такт),
; а потому что её версия на Си неверно собиралась с -O/-Os/-Osir: счётчик
; цикла по строкам инициализировался не нулём, и тело не выполнялось ни разу.
; Без оптимизации тот же исходник работал. См. заметку в шапке проекта.
;
; Адресация через указатель в нулевой странице с индексом Y по байтам строки:
; так на строку приходится всего две записи в указатель, а не восемь
; самомодификаций операндов.
; ---------------------------------------------------------------------------
_clear_px:
        lda     _cp_x
        lsr     a
        sta     cp_x0                   ; первый байт = подшаг / 2

        lda     _cp_x
        clc
        adc     _cp_w
        sec
        sbc     #1                      ; последний подшаг
        pha
        lsr     a
        sta     cp_x1                   ; последний байт

        lda     _cp_x
        and     #1
        tax
        lda     cp_lmask,x
        sta     cp_lm

        pla
        and     #1
        tax
        lda     cp_rmask,x
        sta     cp_rm

        lda     _cp_y
        sta     bl_row
        lda     _cp_h
        sta     bl_cnt

cp_row:
        ldx     bl_row
        lda     _screen_rowlo,x
        sta     cp_ptr
        lda     _screen_rowhi,x
        sta     cp_ptr+1

        ldy     cp_x0
        cpy     cp_x1
        beq     cp_single

        lda     cp_lm                   ; левый неполный байт
        eor     #$FF
        and     (cp_ptr),y
        sta     (cp_ptr),y
        iny

        lda     #0                      ; целые байты между краями
cp_mid: cpy     cp_x1
        beq     cp_right
        sta     (cp_ptr),y
        iny
        bne     cp_mid

cp_right:
        lda     cp_rm                   ; правый неполный байт
        eor     #$FF
        and     (cp_ptr),y
        sta     (cp_ptr),y
        jmp     cp_next

cp_single:                              ; прямоугольник внутри одного байта
        lda     cp_lm
        and     cp_rm
        eor     #$FF
        and     (cp_ptr),y
        sta     (cp_ptr),y

cp_next:
        inc     bl_row
        dec     bl_cnt
        bne     cp_row
        rts

; Гасимые биты первого байта при смещении начала 0..1 подшага
cp_lmask:
        .byte   $FF, $0F
; Гасимые биты последнего байта при смещении конца 0..1 подшага
cp_rmask:
        .byte   $F0, $FF

; ---------------------------------------------------------------------------
; blit_plain - непрозрачный вывод СПЛОШНЫХ данных, без маски и без пропусков.
;
; Отличается от blit_copy тем, что в источнике лежат только байты
; изображения. Спрайты хранятся парами (маска, изображение), а шрифт счёта -
; сплошным массивом, и шагать по нему через байт было бы неверно.
; ---------------------------------------------------------------------------
_blit_plain:
        BLIT_SETUP
        ldy     #0
bp_row:
        SET_ROW_ADDR bp_sta, bp_sta
        ldx     #0
bp_col:
        lda     (_bl_src),y
        iny
bp_sta: sta     $FFFF,x
        inx
        cpx     _bl_w
        bne     bp_col
        inc     bl_row
        dec     bl_cnt
        bne     bp_row
        rts

; ---------------------------------------------------------------------------
; blit_clear - гасит прямоугольник _bl_w x _bl_h байт в чёрный.
; Стирание следа за спрайтом.
; ---------------------------------------------------------------------------
_blit_clear:
        BLIT_SETUP
bl_rowl:
        SET_ROW_ADDR bl_sta, bl_sta
        ldx     _bl_w
        dex
        lda     #0
bl_col:
bl_sta: sta     $FFFF,x
        dex
        bpl     bl_col
        inc     bl_row
        dec     bl_cnt
        bne     bl_rowl
        rts
