#ifndef DEMO_H
#define DEMO_H

#include <stdint.h>

/* Строка растра, в которой лежит телеметрия. Взята в зоне HUD, ниже надписи
 * SCORE и выше поля, чтобы игровая картинка её не затирала. */
#define DEMO_TELEMETRY_Y  26u

/* Порядок байт телеметрии - его же читает tools/telemetry.py:
 *   0,1  номер такта (старший байт первым)
 *   2..4 счёт, упакованный BCD
 *   5    man.x в подшагах
 *   6    man.y в строках растра
 *   7    сколько камней осталось на поле
 *   8    мешков стоит или качается
 *   9    мешков разбилось в золото
 *  10    старший полубайт - врагов на поле, младший - жизней
 *  11    x первого живого врага (подшаги)
 *  12    y первого живого врага (строки растра)
 *  13    его направление
 *  14    сколько раз снаряд был выпущен
 *  15    старший полубайт - погас об землю, младший - ушёл за край
 *  16    старший полубайт - пройдено уровней, младший - номер уровня
 *  17    запущено звуковых эффектов
 *  18    записей в регистры POKEY
 *  19    старший полубайт - состояние бонус-режима, младший - съедено врагов
 */
#define DEMO_TELEMETRY_BYTES  20u

extern uint16_t demo_tick;

void demo_init(void);
uint8_t demo_input(void);
uint8_t demo_finished(void);   /* маршрут пройден, состояние заморожено */
void demo_telemetry(void);

#endif /* DEMO_H */
