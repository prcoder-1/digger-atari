/*
 * hud.c - верхняя панель: счёт, жизни и отладочные числа демо-режима.
 *
 * Панель занимает строки 0..27, поле начинается со строки 28. Символ
 * знакогенератора ПЗУ - 8x8 пикселей, то есть 2 байта экрана и 8 строк.
 *
 * Рисуется панель в тот же кадровый буфер, что и поле, но красками своей пары
 * COL_HUD_*: на границе строк 15/16 стоит прерывание по строке (src/dli.s).
 * Красная полоса короче отведённых панели строк - содержимое кончается на
 * строке 13, строки 16..27 идут уже цветами поля и читаются как отступ.
 */
#include "hud.h"
#include "hw.h"
#include "text.h"
#include "blit.h"

/*
 * Статические данные модуля уезжают в ОЗУ под ПЗУ: MAIN забит под завязку.
 * Обнуляет этот сегмент clear_hi_bss() первым делом в main - стартовый код
 * cc65 сюда не дотягивается, он чистит только сегмент BSS.
 */
#ifdef __CC65__
#pragma bss-name (push, "BSS_HI")
#endif


extern const uint8_t spr_s0_p0[], spr_s0_p1[];  /* значок жизни, две фазы */

extern uint8_t score[3];

#define SCORE_X     1u                  /* байт экрана */
#define SCORE_Y     2u
#define LIVES_Y     2u
#define MAX_LIVES   6u

/*
 * Значки жизней стоят через 20 точек - как в оригинале (print_lives в
 * Work/TF.C ставит их по 60 + loop*20). Спрайт шириной 16 точек, значит между
 * значками остаётся зазор в 4 точки. Вплотную, через 16 точек, они сливались
 * в сплошную ленту.
 *
 * Двадцать точек - это пять подшагов, то есть НЕ целое число байт, поэтому у
 * половины значков берётся сдвинутая фаза спрайта, как у фигур на поле.
 *
 * Шесть значков по 20 точек занимают 120 точек, поэтому ряд начинается с
 * подшага 50 (точка 200) - иначе последний ушёл бы за правый край.
 */
#define LIFE_STEP_SUB   POS_X_STEP      /* 5 подшагов = 20 точек */
#define LIVES_X_SUB     50u
/* Значок жизни НИЖЕ обычного спрайта: 16x12, а не 16x15. Раньше выводились
 * все 15 строк, и три лишние блиттер дочитывал из следующего спрайта - под
 * значками висел мусор. */
#define LIFE_H      12u

static uint8_t lives_shown = 0xFF;

void hud_init(void)
{
    lives_shown = 0xFF;
    /* Подписи SCORE нет: в оригинале счёт стоит сам по себе */
}

void hud_score(void)
{
    text_bcd6(SCORE_X, SCORE_Y, score);
}

void hud_lives(uint8_t n)
{
    uint8_t i;

    if (n == lives_shown)
        return;
    lives_shown = n;

    if (n > MAX_LIVES)
        n = MAX_LIVES;

    /* Полоса значков перерисовывается целиком: она короткая, а следить за
     * тем, какой именно значок пропал, дороже, чем стереть и нарисовать. */
    cp_x = LIVES_X_SUB;
    cp_y = LIVES_Y;
    cp_w = (uint8_t)(MAX_LIVES * LIFE_STEP_SUB);
    cp_h = LIFE_H;
    clear_px();

    for (i = 0; i < n; ++i) {
        uint8_t xs = (uint8_t)(LIVES_X_SUB + i * LIFE_STEP_SUB);

        bl_x = (uint8_t)(xs >> 1);
        bl_y = LIVES_Y;
        bl_h = LIFE_H;
        if (xs & 1u) {
            bl_w = 3u;
            bl_src = spr_s0_p1;
        } else {
            bl_w = 2u;
            bl_src = spr_s0_p0;
        }
        blit_mask();
    }
}

#ifdef __CC65__
#pragma bss-name (pop)
#endif
